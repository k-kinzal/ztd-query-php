    private const CATALOG17 = [
        'pg_stat_checkpointer' => true,
        'pg_wait_events' => true,
    ];

    /**
     * Tells whether a stock relation occupies this exact coordinate.
     */
    public static function contains(GrammarRelease $release, Name $schema, Name $name): bool
    {
        return match ($schema->value) {
            'pg_catalog' => isset(self::CATALOG[$name->value])
                || ($release === GrammarRelease::PostgreSql172 && isset(self::CATALOG17[$name->value])),
            'information_schema' => InformationSchemaNames::contains($name),
            default => false,
        };
    }
