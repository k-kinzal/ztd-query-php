<?php

declare(strict_types=1);

namespace SqlSemantics\Platform\PostgreSql\Statement\Constraint\Column;

use SqlSemantics\Construction\Derivation;
use SqlSemantics\Platform\PostgreSql\Rules\Table\Writing;
use SqlSemantics\Platform\PostgreSql\Statement\Constraint\Constraint;
use SqlSemantics\Platform\PostgreSql\Statement\Constraint\ConstraintKind;
use SqlSemantics\Platform\PostgreSql\Statement\Table\Problem\DefinitionProblem;
use SqlSemantics\Platform\PostgreSql\Statement\Table\Problem\DefinitionRule;
use SqlSemantics\Rendering\Output;
use SqlSemantics\Resolution\Environment;
use SqlSemantics\Statement\Identifier\Name;
use SqlSemantics\Statement\Scalar;
use SqlSemantics\Statement\Snapshot;

/**
 * A GENERATED ... AS ( expression ) STORED column constraint: the column always holds the value of an expression of the other columns.
 *
 * Mirrors `CONSTR_GENERATED` with `raw_expr`. The expression is derived
 * where the columns of the table are visible. A generated column can be NULL.
 * The server requires GENERATED ALWAYS: "for a generated column, GENERATED
 * ALWAYS must be specified" is a diagnostic.
 * Source: https://www.postgresql.org/docs/17/sql-createtable.html, https://www.postgresql.org/docs/17/ddl-generated-columns.html.
 *
 * @visibility public
 * @example A generated column refers to other columns
 *     $create = (new \SqlSemantics\Facade\Semantics(\SqlSemantics\Platform\PostgreSql\Dialect::PostgreSql))->analyze('CREATE TABLE t (a int, b int GENERATED ALWAYS AS (a * 2) STORED)');
 *     $generated = $create->statement->definition->elements[1]->qualifiers[0];
 *     $create->facts->scalar($generated->expression->left)->resolution->slot->column === $create->declarations()[0]->columns[0] // => true
 */
final class Generated implements Constraint
{
    use Snapshot;

    /**
     * @param GeneratedWhen $when When the column takes the generated value
     * @param Scalar $expression The generation expression
     * @param Name|null $name The constraint name
     */
    public function __construct(public readonly GeneratedWhen $when, public readonly Scalar $expression, public readonly ?Name $name = null)
    {
    }

    /**
     * Answers the kind of the constraint.
     */
    public function kind(): ConstraintKind
    {
        return ConstraintKind::Generated;
    }

    /**
     * Derives the expression against the table and reports GENERATED BY DEFAULT.
     */
    public function deriveClause(Derivation $derivation, Environment $environment): void
    {
        $derivation->scalar($this->expression, $environment);
        if ($this->when === GeneratedWhen::ByDefault) {
            $derivation->report(new DefinitionProblem(DefinitionRule::GeneratedByDefault));
        }
    }

    /**
     * Writes the constraint.
     */
    public function render(Output $out): void
    {
        (new Writing())->constraintName($out, $this->name);
        $out->keyword('GENERATED', ...$this->when->keywords())->keyword('AS')->symbol('(')->node($this->expression)->symbol(')')->keyword('STORED');
    }
}
