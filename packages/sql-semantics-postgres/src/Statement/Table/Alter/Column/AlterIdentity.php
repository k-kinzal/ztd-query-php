<?php

declare(strict_types=1);

namespace SqlSemantics\Platform\PostgreSql\Statement\Table\Alter\Column;

use SqlSemantics\Construction\Derivation;
use SqlSemantics\Platform\PostgreSql\Rules\Table\Command\Alterations;
use SqlSemantics\Platform\PostgreSql\Rules\Table\Command\IdentityChanges;
use SqlSemantics\Platform\PostgreSql\Rules\Table\Writing;
use SqlSemantics\Platform\PostgreSql\Statement\Table\Alter\AlterCommand;
use SqlSemantics\Rendering\Output;
use SqlSemantics\Resolution\Environment;
use SqlSemantics\Statement\Identifier\Name;
use SqlSemantics\Statement\Snapshot;

/**
 * ALTER [ COLUMN ] ... SET/RESTART: changes the sequence or the generation of an identity column.
 *
 * Mirrors `AT_SetIdentity` with its options in the order written.
 * Source: https://www.postgresql.org/docs/17/sql-altertable.html.
 *
 * @visibility public
 * @example Changing an identity
 *     $statement = (new \SqlSemantics\Facade\Semantics(\SqlSemantics\Platform\PostgreSql\Dialect::PostgreSql))->analyze('ALTER TABLE t ALTER a SET GENERATED BY DEFAULT RESTART WITH 5 SET INCREMENT 2');
 *     $statement->toString() // => 'ALTER TABLE t ALTER a SET GENERATED BY DEFAULT RESTART 5 SET INCREMENT 2'
 */
final class AlterIdentity implements AlterCommand
{
    use Snapshot;

    /**
     * @var non-empty-list<IdentityRestart|IdentitySetting|IdentityGeneration> The changes in the order written
     */
    public readonly array $options;

    /**
     * @param Name $column The column
     * @param list<IdentityRestart|IdentitySetting|IdentityGeneration> $options The changes in the order written
     */
    public function __construct(public readonly Name $column, array $options)
    {
        $this->options = (new IdentityChanges())->checked($options);
    }

    /**
     * Checks that the column exists.
     */
    public function deriveClause(Derivation $derivation, Environment $environment): void
    {
        (new Alterations())->column($derivation, $environment, $this->column);
    }

    /**
     * Writes the action.
     */
    public function render(Output $out): void
    {
        $out->keyword('ALTER')->name($this->column);
        (new Writing())->sequence($out, $this->options);
    }
}
