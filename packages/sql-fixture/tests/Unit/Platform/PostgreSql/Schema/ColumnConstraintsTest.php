<?php

declare(strict_types=1);

namespace Tests\Unit\Platform\PostgreSql\Schema;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\TestCase;
use SqlFixture\Platform\PostgreSql\Schema\ColumnConstraints as Subject;
use SqlParser\PostgreSql\PostgreSqlParser;

#[CoversClass(Subject::class)]
#[\PHPUnit\Framework\Attributes\UsesClass(\SqlFixture\Syntax\NodeReader::class)]
final class ColumnConstraintsTest extends TestCase
{
    public function testReadDefaultsToANullableColumn(): void
    {
        $tree = (new PostgreSqlParser())->parse('CREATE TABLE t (id INT)');
        $constraints = (new Subject())->read($tree->find('columnDef')[0]);

        self::assertTrue($constraints->nullable);
        self::assertFalse($constraints->primaryKey);
        self::assertFalse($constraints->identity);
        self::assertFalse($constraints->generated);
        self::assertNull($constraints->default);
    }

    public function testReadRecognizesNotNullDefaultPrimaryKeyAndCollation(): void
    {
        $sql = "CREATE TABLE t (id TEXT COLLATE \"C\" NOT NULL DEFAULT 'x' PRIMARY KEY UNIQUE CHECK (id <> ''))";
        $tree = (new PostgreSqlParser())->parse($sql);
        $constraints = (new Subject())->read($tree->find('columnDef')[0]);

        self::assertFalse($constraints->nullable);
        self::assertTrue($constraints->primaryKey);
        self::assertNotNull($constraints->default);
        self::assertSame("'x'", $constraints->default->text($sql));
    }

    public function testReadLetsAnExplicitNullFollowNotNull(): void
    {
        $tree = (new PostgreSqlParser())->parse('CREATE TABLE t (a INT NOT NULL NULL)');

        self::assertTrue((new Subject())->read($tree->find('columnDef')[0])->nullable);
    }

    public function testReadDistinguishesIdentityFromGeneratedColumns(): void
    {
        $tree = (new PostgreSqlParser())->parse('CREATE TABLE t (a INT GENERATED ALWAYS AS IDENTITY, b INT GENERATED BY DEFAULT AS IDENTITY, c INT GENERATED ALWAYS AS (a + 1) STORED)');
        $definitions = $tree->find('columnDef');

        self::assertTrue((new Subject())->read($definitions[0])->identity);
        self::assertFalse((new Subject())->read($definitions[0])->generated);
        self::assertTrue((new Subject())->read($definitions[1])->identity);
        self::assertTrue((new Subject())->read($definitions[2])->generated);
        self::assertFalse((new Subject())->read($definitions[2])->identity);
    }
}
