<?php

declare(strict_types=1);

namespace Tests\Unit\Platform\PostgreSql\Schema;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\TestCase;
use SqlFixture\Platform\PostgreSql\Schema\ColumnConstraints as Subject;
use Tests\Statement\PostgreSqlStatements;

#[CoversClass(Subject::class)]
#[\PHPUnit\Framework\Attributes\UsesClass(\SqlFixture\Platform\PostgreSql\Schema\TableDefinition::class)]
final class ColumnConstraintsTest extends TestCase
{
    public function testReadDefaultsToAPlainColumn(): void
    {
        $constraints = (new Subject())->read(PostgreSqlStatements::columns('a INT NOT NULL')[0]->qualifiers);

        self::assertFalse($constraints->primaryKey);
        self::assertFalse($constraints->identity);
        self::assertNull($constraints->default);
    }

    public function testReadRecognizesPrimaryKeyIdentityAndDefault(): void
    {
        $qualifiers = array_map(static fn ($column): array => $column->qualifiers, PostgreSqlStatements::columns('a INT CONSTRAINT pk PRIMARY KEY, b INT GENERATED BY DEFAULT AS IDENTITY, c INT DEFAULT 1'));

        self::assertTrue((new Subject())->read($qualifiers[0])->primaryKey);
        self::assertTrue((new Subject())->read($qualifiers[1])->identity);
        self::assertNotNull((new Subject())->read($qualifiers[2])->default);
    }
}
