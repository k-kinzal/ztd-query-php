    public function testSelectedDoesNotExpandMethodsThatCannotWriteAnInitializedReadonlyField(): void
    {
        $source = new Source('candidate.php', '<?php class A{public function __construct(public readonly int $x){} public function touch($flag){if($flag){return external();}return other();}}function target($flag){$a=new A(7);$a->touch($flag);return $a->x;}');
        $tree = (new Resolver())->resolve((new Parser(new ParserConfig('8.1')))->parse($source));
        $index = new DefinitionIndex(new Index('test', [$tree]));
        $engine = new Evaluator(new Context($index, new EvaluatorConfig(), new Evaluators(), new Budget()));
        $graph = $index->graph('target');
        self::assertNotNull($graph);

        $value = $engine->returns(new Frame($graph, 'source:target'), 64);

        self::assertSame(7, $value->native());
        self::assertArrayNotHasKey('A::touch', $engine->context->bodies);
        self::assertNull($engine->context->stopReason);
    }

    public function testSelectedFollowsReadonlyInitializersOutsideConstructors(): void
    {
        $source = new Source('candidate.php', '<?php class A{public readonly int $x;public function initialize(){$this->x=9;}}function target(){$a=new A;$a->initialize();return $a->x;}');
