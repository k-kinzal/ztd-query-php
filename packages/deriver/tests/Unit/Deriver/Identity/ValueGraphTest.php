final class ValueGraphTest extends TestCase
{
    public function testAddPreservesTheSemanticContract(): void
    {
        $graph = new ValueGraph();
        $root = $graph->add(Term::fromNative([2 => 'a', 'name' => 'b']));
        self::assertSame('array', $graph->records[$root]['kind']);
        $operands = $graph->records[$root]['operands'];
        self::assertSame(['type' => 'int64', 'value' => '2'], $operands[0]['key']);
        self::assertSame(['type' => 'bytes', 'value' => base64_encode('name')], $operands[1]['key']);
        self::assertSame(['type' => 'bytes', 'value' => base64_encode('a')], $graph->records[$operands[0]['value']]['literal']);
    }
    public function testScalarPreservesSignedZeroAndBinaryStrings(): void
    {
        $graph = new ValueGraph();
        self::assertSame(['type' => 'float64', 'value' => '8000000000000000'], $graph->scalar(-0.0));
        self::assertSame(['type' => 'bytes', 'value' => '/wA='], $graph->scalar("\xff\x00"));
    }
    public function testMappingSharesReferencesForEqualTerms(): void
    {
        $graph = new ValueGraph();
        $mapping = $graph->mapping(['a' => Term::constant(3), 'b' => Term::constant(3)]);
        self::assertSame($mapping['a'], $mapping['b']);
        self::assertCount(1, $graph->records);
    }
    public function testAddEncodesSharedSubgraphsWithoutExpandingTheTree(): void
    {
        $depth = 64;
        $leaf = Term::constant(1);
        $leaf = array_reduce(array_fill(0, $depth, null), static fn (Term $leaf): Term => Term::array([$leaf, $leaf]), $leaf);
        $value = $leaf;
        $graph = new ValueGraph();
        self::assertSame('v0', $graph->add($value));
        self::assertCount(65, $graph->records);
        self::assertSame($graph->records['v0']['operands'][0]['value'], $graph->records['v0']['operands'][1]['value']);
    }
}
