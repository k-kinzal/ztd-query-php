        self::assertSame(ValuePrecision::Opaque, $assessment->precision(new Term(TermKind::Object, 'object'), $storage));
        self::assertSame(ValuePrecision::ExactSymbolic, $assessment->precision(new Term(TermKind::Object, 'untracked'), $storage));
