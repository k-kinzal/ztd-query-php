final class PropertyScopeTest extends TestCase
{
    public function testGraphKeepsProvenanceWhileBindingSelfToTheConsumer(): void
    {
        $source = '<?php trait T{public $x=self::C;}class B{use T;const C=4;}';
        $snapshotId = 'test';
        $input = new Sources([new Source('fixture.php', $source)]);
        $profile = new TargetProfile();
        $parser = new Parser(new ParserConfig($profile->version));
        $trees = array_map(static fn (Source $source1): File => (new Resolver())->resolve($parser->parse(new Source(Path::normalize($source1->path), $source1->contents, $source1->declarationsOnly))), iterator_to_array($input, false));
        $index = new Index($snapshotId, $trees);
        $default = $index->classes()['b']->properties['x']->default;
        self::assertNotNull($default);
        self::assertSame('B', $default->className);
        self::assertSame('fixture.php', $default->source->path);
        self::assertStringContainsString('trait-property:', $default->symbol);
    }
}
