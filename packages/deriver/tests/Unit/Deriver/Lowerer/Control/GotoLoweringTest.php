        $graph = (new Index($snapshotId, $trees))->callable('target');
        self::assertNotNull($graph);
        self::assertSame([], array_filter($graph->blocks, static fn ($block) => $block->loopHeader));
    }
    public function testResolveReleasesForeachIteratorsAfterNestedFinallyBlocks(): void
    {
        $source = '<?php function target(){foreach([1] as $v){try{goto out;}finally{$v=2;}}out:return 1;}';
        $snapshotId = 'test';
        $input = new Sources([new Source('fixture.php', $source)]);
        $profile = new TargetProfile();
        $parser = new Parser(new ParserConfig($profile->version));
        $trees = array_map(static fn (Source $source1): File => (new Resolver())->resolve($parser->parse(new Source(Path::normalize($source1->path), $source1->contents, $source1->declarationsOnly))), iterator_to_array($input, false));
        $graph = (new Index($snapshotId, $trees))->callable('target');
        self::assertNotNull($graph);
        $jumps = array_values(array_filter($graph->blocks, static fn ($block) => $block->terminator->kind === TerminatorKind::CompleteJump));
        self::assertCount(2, $jumps);
        self::assertSame(0, $jumps[0]->terminator->handlerDepth);
        $release = $graph->blocks[$jumps[0]->terminator->targets[0]];
        self::assertSame(['iterator-release'], array_column($release->instructions, 'operation'));
        self::assertSame(TerminatorKind::CompleteJump, $release->terminator->kind);
    }
