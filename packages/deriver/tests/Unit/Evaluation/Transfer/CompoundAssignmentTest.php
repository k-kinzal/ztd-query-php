final class CompoundAssignmentTest extends TestCase
{
    /**
     * @throws JsonException If the fixture observation cannot be encoded
     */
    public function testApplyReadsStorageAfterRightOperandEffects(): void
    {
        $result = \Tests\Fake\Analysis::returns('<?php function target(){$a=1;$a+=($a=2);return $a;}');
        self::assertSame(4, $result->normalOutcomes[0]->values['return']->native());
        self::assertSame([], $result->exceptionalOutcomes);
    }
    /**
     * @throws JsonException If the fixture observation cannot be encoded
     */
    public function testApplyRetainsArrayCreationWhenTheOperatorThrows(): void
    {
        $result = \Tests\Fake\Analysis::returns('<?php function target(){$a=null;try{$a[0]+=new stdClass;}catch(TypeError $e){return $a;}return 999;}');
        self::assertSame([null], $result->normalOutcomes[0]->values['return']->native());
        self::assertSame(['PHP_WARNING'], array_column($result->frontiers, 'code'));
    }
}
