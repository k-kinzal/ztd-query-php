final class BindingTest extends TestCase
{
    public function testScopeKeepsCallerCoercionModeAndCapturedAccessRights(): void
    {
        $context = \Tests\Fake\SolverFixture::context();
        $body = $context->program->callable('target');
        self::assertNotNull($body);
        $machine = new Machine($context);
        $state = new State();
        $instruction = new Instruction('arg', 'argument', $body->source, 'result', ['prepared', 'input']);

        $caller = new CallableGraph('caller', [], [], $body->source, strict: true, className: 'Outside');
        $scope = (new Binding($machine))->scope(new Term('closure', attributes: ['scope' => 'Inside']), $caller);
        self::assertSame('Inside', $scope->className);
        self::assertTrue($scope->strict);
    }
    public function testStateRestoresCapturedThisWithoutChangingTheInvokingFrame(): void
    {
        $context = \Tests\Fake\SolverFixture::context();
        $body = $context->program->callable('target');
        self::assertNotNull($body);
        $machine = new Machine($context);
        $state = new State();
        $instruction = new Instruction('arg', 'argument', $body->source, 'result', ['prepared', 'input']);

        $original = $state->local('this');
        $state->memory->write($original, new Term('object', 'outside', attributes: ['class' => 'Outside']));
        $captured = new Term('object', 'inside', attributes: ['class' => 'Inside']);
        $closure = new Term('closure', operands: ['this' => $captured], attributes: ['late-static' => 'Inside']);
        $bound = (new Binding($machine))->state($closure, $state);
        self::assertSame('inside', $bound->memory->read($bound->locals['this'])->literal);
        self::assertSame('outside', $state->memory->read($original)->literal);
        self::assertSame('Inside', $bound->lateStaticClass);
    }
    /**
     * @throws JsonException If captured fixture metadata cannot be encoded
     */
    public function testSignaturePreservesPrivateReferenceParametersAfterEscape(): void
    {
        $result = \Tests\Fake\Analysis::returns('<?php class Box{private function set(&$x){$x=2;}function callback(){return $this->set(...);}}function target(){$f=(new Box)->callback();$f($a);return $a;}');
        self::assertSame(2, $result->normalOutcomes[0]->values['return']->native());
        self::assertSame([], array_column($result->frontiers, 'code'));
        self::assertSame([], $result->exceptionalOutcomes);
    }
    /**
     * @throws JsonException If captured fixture metadata cannot be encoded
     */
    public function testInvokeRestoresTheCallingObjectAndLateStaticContext(): void
    {
        $result = \Tests\Fake\Analysis::returns('<?php class A{public $x=1;function value(){return $this->x;}function callback(){return self::value(...);}}class B{public $x=2;function run($f){return [$f(),$this->x];}}function target(){$f=(new A)->callback();return (new B)->run($f);}');
        self::assertSame([1, 2], $result->normalOutcomes[0]->values['return']->native());
        self::assertSame([], array_column($result->frontiers, 'code'));
        self::assertSame([], $result->exceptionalOutcomes);
    }
}
