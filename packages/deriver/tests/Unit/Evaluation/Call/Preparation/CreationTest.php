final class CreationTest extends TestCase
{
    /**
     * @throws JsonException If captured fixture metadata cannot be encoded
     */
    public function testResolveRejectsPrivateConstructorsBeforeTheirArgumentEffects(): void
    {
        $result = \Tests\Fake\Analysis::returns('<?php class Box{private function __construct($x){}}function target(){$a=1;try{new Box($a=2);}catch(Error $e){return $a;}return 999;}');
        self::assertSame(1, $result->normalOutcomes[0]->values['return']->native());
        self::assertSame([], array_column($result->frontiers, 'code'));
        self::assertSame([], $result->exceptionalOutcomes);
    }
    /**
     * @throws JsonException If captured fixture metadata cannot be encoded
     */
    public function testResolveRecognizesInheritedReferenceConstructors(): void
    {
        $result = \Tests\Fake\Analysis::returns('<?php class Base{function __construct(&$x){$x=2;}}class Child extends Base{}function target(){$a=[];new Child($a[0]);return $a;}');
        self::assertSame([2], $result->normalOutcomes[0]->values['return']->native());
        self::assertSame([], array_column($result->frontiers, 'code'));
        self::assertSame([], $result->exceptionalOutcomes);
    }
    public function testResolveObtainsNativeThrowableSignatures(): void
    {
        $context = \Tests\Fake\SolverFixture::context();
        $body = $context->program->callable('target');
        self::assertNotNull($body);
        $machine = new Machine($context);
        $state = new State();
        $instruction = new Instruction('arg', 'argument', $body->source, 'result', ['prepared', 'input']);

        $state->registers['class'] = Term::constant('Exception');
        $creation = new Instruction('new', 'new', $body->source, 'result', ['class']);
        $target = (new Creation($machine))->resolve($body, $creation, $state);
        self::assertNotNull($target->signature);
        self::assertSame('message', $target->signature->parameters[0]->name);
        self::assertSame('', $target->error);
    }

    /**
     * @throws JsonException If fixture metadata cannot be encoded
     */
    #[\PHPUnit\Framework\Attributes\DataProviderExternal(\Tests\Fake\Programs\DynamicClassPrograms::class, 'allocations')]
    public function testResolveSeparatesLiteralAndRuntimeClassOperands(string $source, string $expected): void
    {
        $result = \Tests\Fake\Analysis::returns($source);
        self::assertSame([], $result->frontiers);
        self::assertSame([], $result->projectDiagnostics);
        self::assertSame([], $result->exceptionalOutcomes);
        self::assertCount(1, $result->normalOutcomes);
        self::assertSame(json_decode($expected, true, flags:JSON_THROW_ON_ERROR), $result->normalOutcomes[0]->values['return']->native());
    }
}
