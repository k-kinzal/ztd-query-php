final class CallLoweringTest extends TestCase
{
    /**
     * @throws JsonException If captured metadata cannot be encoded
     */
    public function testLowerPreservesTheSemanticContract(): void
    {
        $result = \Tests\Fake\Analysis::returns('<?php function tagged(string $tag,int $id) { return $tag . ":" . $id; } function target() { return [tagged("user",1),tagged("item",2)]; }');
        self::assertSame(['user:1', 'item:2'], $result->normalOutcomes[0]->values['return']->native());
        self::assertSame([], $result->frontiers);
        self::assertSame([], $result->exceptionalOutcomes);
    }
    public function testNullsafeUsesThePreviouslyEvaluatedReceiver(): void
    {
        $l = \Tests\Fake\SourceFixture::lowering();
        $node = new \PhpParser\Node\Expr\NullsafeMethodCall(new \PhpParser\Node\Expr\FuncCall(new \PhpParser\Node\Name('receiver')), 'run');
        (new CallLowering($l))->nullsafe($node, 'receiver-once');
        self::assertSame(['constant', 'call-prepare', 'invoke-method'], array_column($l->graph->instructions[0], 'operation'));
        self::assertSame('receiver-once', $l->graph->instructions[0][1]->operands[0]);
    }
    /**
     * @throws JsonException If captured fixture metadata cannot be encoded
     */
    public function testInvokeCapturesTheSignatureBeforeArgumentSideEffects(): void
    {
        $result = \Tests\Fake\Analysis::returns('<?php class Box{private static function hidden($x){}}function target(){$x=1;try{Box::hidden($x=2);}catch(Error $e){return $x;}return 999;}');
        self::assertSame(1, $result->normalOutcomes[0]->values['return']->native());
        self::assertSame([], array_column($result->frontiers, 'code'));
        self::assertSame([], $result->exceptionalOutcomes);
    }

    #[\PHPUnit\Framework\Attributes\DataProvider('providerClassOperandSyntax')]
    public function testLowerPreservesWhetherAClassOperandIsLiteral(string $expression, bool $literal): void
    {
        $index = \Tests\Fake\SourceFixture::index('<?php function target($class,$value){return ' . $expression . ';}');
        $body = $index->callable('target');
        self::assertNotNull($body);
        $instructions = array_values(array_filter($body->blocks[0]->instructions, static fn (Instruction $instruction): bool => $instruction->operation === 'invoke-static'));
        self::assertCount(1, $instructions);
        self::assertSame($literal, $instructions[0]->attributes['literal-class']);
    }

    /**
     * @return iterable<string,array{string,bool}>
     */
    public static function providerClassOperandSyntax(): iterable
    {
        yield 'Box::value()' => ['Box::value()', true];
        yield '$class::value()' => ['$class::value()', false];
    }
}
