#[Small]
final class MatchLoweringTest extends TestCase
{
    /**
     * @throws JsonException If captured metadata cannot be encoded
     */
    public function testArmsPreservesTheSemanticContract(): void
    {
        $result = \Tests\Fake\Analysis::returns('<?php function target(){return match(2){1=>"a",2=>"b",default=>"c"};}');
        self::assertSame('b', $result->normalOutcomes[0]->values['return']->native());
        self::assertSame([], $result->frontiers);
        self::assertSame([], $result->exceptionalOutcomes);
    }
    public function testConditionsUsesStrictComparisonAndTheSharedSubject(): void
    {
        $l = \Tests\Fake\SourceFixture::lowering();
        $node = new \PhpParser\Node\Expr\Match_(new \PhpParser\Node\Expr\Variable('x'), [new \PhpParser\Node\MatchArm([new \PhpParser\Node\Scalar\Int_(1)], new \PhpParser\Node\Scalar\String_('one'))]);
        (new MatchLowering($l))->conditions($node, 'subject-once', 0, 0);
        self::assertSame('===', $l->graph->instructions[0][1]->name);
        self::assertSame('subject-once', $l->graph->instructions[0][1]->operands[0]);
    }
}
