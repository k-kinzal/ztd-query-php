final class LoopLoweringTest extends TestCase
{
    /**
     * @throws JsonException If captured metadata cannot be encoded
     */
    public function testLowerPreservesTheSemanticContract(): void
    {
        $result = \Tests\Fake\Analysis::returns('<?php function target(){ $a=[1,2,3];foreach($a as &$x){}$x=4;unset($x);$x=5;return $a;}');
        self::assertSame([1, 2, 4], $result->normalOutcomes[0]->values['return']->native());
        self::assertSame([], $result->frontiers);
        self::assertSame([], $result->exceptionalOutcomes);
    }
    public function testInitializeTakesAnAddressForReferenceForeach(): void
    {
        $l = \Tests\Fake\SourceFixture::lowering();
        $node = new \PhpParser\Node\Stmt\Foreach_(new \PhpParser\Node\Expr\Variable('items'), new \PhpParser\Node\Expr\Variable('item'), ['byRef' => true]);
        (new LoopLowering($l))->initialize($node);
        self::assertSame(['local', 'iterator'], array_column($l->graph->instructions[0], 'operation'));
        self::assertTrue($l->graph->instructions[0][1]->attributes['byReference']);
    }
    public function testConditionUsesTrueForAnOmittedForCondition(): void
    {
        $l = \Tests\Fake\SourceFixture::lowering();
        (new LoopLowering($l))->condition(new \PhpParser\Node\Stmt\For_(), '');
        self::assertSame(true, $l->graph->instructions[0][0]->constant?->native());
    }
    public function testBindIterationAliasesTheActualElementForReferenceForeach(): void
    {
        $l = \Tests\Fake\SourceFixture::lowering();
        $node = new \PhpParser\Node\Stmt\Foreach_(new \PhpParser\Node\Expr\Variable('items'), new \PhpParser\Node\Expr\Variable('item'), ['byRef' => true]);
        (new LoopLowering($l))->bindIteration($node, 'iterator');
        self::assertSame(['iterator-address', 'local', 'alias'], array_column($l->graph->instructions[0], 'operation'));
    }
    public function testCompletionResolvesTheRequestedEnclosingLoopAndHandlerDepth(): void
    {
        $l = \Tests\Fake\SourceFixture::lowering();
        $l->graph->loops = [['break' => 8, 'continue' => 7, 'depth' => 1], ['break' => 5, 'continue' => 4, 'depth' => 2]];
        (new LoopLowering($l))->completion(new \PhpParser\Node\Stmt\Continue_(new \PhpParser\Node\Scalar\Int_(2)));
        self::assertSame([7], $l->graph->terminators[0]->targets);
        self::assertSame(1, $l->graph->terminators[0]->handlerDepth);
    }

    /**
     * @throws JsonException If recorded observations cannot be decoded
     */
    #[\PHPUnit\Framework\Attributes\DataProvider('providerForeachSemantics')]
    public function testBindIterationPreservesRecordedPatternSemantics(string $source, string $normalJson, string $exception, bool $diagnostic): void
    {
        $expected = json_decode($normalJson, true, 512, JSON_THROW_ON_ERROR);
        $result = \Tests\Fake\Analysis::returns($source);
        self::assertSame($expected, array_map(static fn (Alternative $outcome) => $outcome->values['return']->native(), $result->normalOutcomes));
        self::assertSame($exception === '' ? [] : [$exception], array_map(static fn (Exceptional $outcome): int|float|string|bool|null => $outcome->exception->literal, $result->exceptionalOutcomes));
        self::assertSame($diagnostic, in_array('PHP_WARNING', array_column($result->frontiers, 'code'), true));
        self::assertSame([], array_diff(array_column($result->frontiers, 'code'), ['PHP_WARNING']));
    }

    /**
     * @return iterable<string,array{string,string,string,bool}>
     */
    public static function providerForeachSemantics(): iterable
    {
        foreach (\Tests\Fake\Programs\DestructuringPrograms::cases() as $name => $case) {
            if (str_starts_with($name, 'foreach')) {
                yield $name => $case;
            }
        }
    }
}
