final class StaticLoweringTest extends TestCase
{
    /**
     * @throws JsonException If captured metadata cannot be encoded
     */
    public function testLowerGuardsTheInitializerWithItsStorageState(): void
    {
        $result = \Tests\Fake\Analysis::returns('<?php function nextValue(){static $n=0;return ++$n;}function f(){static $n=nextValue();return $n;}function target(){return [f(),f(),nextValue()];}');
        self::assertSame([], $result->frontiers);
        self::assertSame([], $result->exceptionalOutcomes);
        self::assertCount(1, $result->normalOutcomes);
        self::assertSame([1, 1, 2], $result->normalOutcomes[0]->values['return']->native());
    }
}
