<?php

declare(strict_types=1);

namespace Tests\Eris;

use Eris\Generator;
use Eris\Generator\GeneratedValue;
use Eris\Generator\GeneratedValueOptions;
use Eris\Generator\GeneratedValueSingle;
use Eris\Generators;
use Eris\Random\RandomRange;
use LogicException;
use Override;
use Traversable;
use WeakMap;

/**
 * Uses Eris sequence generation and shrinks by removing or reducing one element.
 * Removing any position preserves the other generated inputs, so a later failing
 * action remains reachable while earlier, unrelated actions disappear.
 *
 * @template T
 * @implements Generator<list<T>>
 */
final class Sequence implements Generator
{
    /** @var Generator<list<T>> */
    private readonly Generator $delegate;

    /** @var WeakMap<GeneratedValueSingle<list<T>>, list<T>> */
    private readonly WeakMap $values;

    /**
     * @param Generator<T> $elements
     */
    public function __construct(private readonly Generator $elements)
    {
        $this->delegate = Generators::seq($elements);
        $this->values = new WeakMap();
    }

    /**
     * @param int $size
     * @return GeneratedValueSingle<list<T>>
     */
    #[Override]
    public function __invoke($size, RandomRange $rand): GeneratedValueSingle
    {
        $generated = ($this->delegate)($size, $rand);
        $result = GeneratedValueSingle::fromValueAndInput($generated->unbox(), $generated->input(), 'sequence');
        $this->values[$result] = $generated->unbox();
        return $result;
    }

    /**
     * @param GeneratedValue<mixed> $sequence
     * @return GeneratedValue<list<T>>
     * @throws LogicException When the value was not generated by this sequence
     */
    #[Override]
    public function shrink(GeneratedValue $sequence): GeneratedValue
    {
        $original = $this->values[$sequence] ?? throw new LogicException('A sequence retains its original Eris values.');
        $input = $sequence->input();
        if (!is_array($input) || !array_is_list($input) || count($input) !== count($original)) {
            throw new LogicException('A sequence retains a matching list of Eris inputs.');
        }
        foreach ($input as $value) {
            if (!$value instanceof GeneratedValue) {
                throw new LogicException('Sequence elements retain their Eris generation inputs.');
            }
        }
        return new Options(function () use ($input, $original): Traversable {
            $emitted = false;
            foreach (array_keys($original) as $index) {
                $values = $original;
                $inputs = $input;
                unset($values[$index], $inputs[$index]);
                $values = array_values($values);
                $result = GeneratedValueSingle::fromValueAndInput($values, array_values($inputs), 'sequence');
                $this->values[$result] = $values;
                $emitted = true;
                yield $result;
            }
            foreach ($input as $index => $value) {
                foreach ($this->elements->shrink($value) as $candidate) {
                    if ((new GeneratedValueOptions([$candidate]))->remove($value)->count() === 0) {
                        continue;
                    }
                    $values = $original;
                    $values[$index] = $candidate->unbox();
                    $inputs = $input;
                    $inputs[$index] = $candidate;
                    $values = array_values($values);
                    $result = GeneratedValueSingle::fromValueAndInput($values, $inputs, 'sequence');
                    $this->values[$result] = $values;
                    $emitted = true;
                    yield $result;
                }
            }
            if (!$emitted) {
                $result = GeneratedValueSingle::fromValueAndInput($original, $input, 'sequence');
                $this->values[$result] = $original;
                yield $result;
            }
        });
    }
}
