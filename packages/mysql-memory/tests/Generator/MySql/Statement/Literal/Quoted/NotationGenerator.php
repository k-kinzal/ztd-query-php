<?php

declare(strict_types=1);

namespace Tests\Generator\MySql\Statement\Literal\Quoted;

use Eris\Generator as ErisGenerator;
use Eris\Generators;
use SqlSemantics\Platform\MySql\Statement\Literal\Quoted\Escape;
use SqlSemantics\Platform\MySql\Statement\Literal\Quoted\Notation;
use Tests\Generator\Composition;

/**
 * @implements ErisGenerator<Notation>
 */
final class NotationGenerator implements ErisGenerator
{
    /**
     * @use Composition<Notation>
     */
    use Composition;

    /**
     * @param ErisGenerator<array<int, Escape>>|null $escapes Applicable escapes indexed by decoded byte
     */
    public function __construct(?ErisGenerator $escapes = null)
    {
        $this->delegate = Generators::bind(Generators::tuple(Generators::bool(), Generators::bool()), static fn (array $flags): ErisGenerator => Generators::map(static fn (array $selected): Notation => new Notation($flags[0], $selected, $flags[1]), $flags[1] ? ($escapes ?? Generators::constant([])) : Generators::constant([])));
    }

    /**
     * Composes escape choices that remain compatible with the generated bytes.
     * @return ErisGenerator<Notation>
     */
    public static function forValue(string $value): ErisGenerator
    {
        if ($value === '') {
            return new self();
        }
        $escapes = Generators::bind(Generators::choose(0, strlen($value) - 1), static function (int $offset) use ($value): ErisGenerator {
            $choices = array_values(array_filter(Escape::cases(), static fn (Escape $escape): bool => $escape->bytes() === null ? Escape::tryFrom($value[$offset]) === null : substr($value, $offset, strlen($escape->bytes())) === $escape->bytes()));
            return $choices === [] ? Generators::constant([]) : Generators::map(static fn (Escape $escape): array => [$offset => $escape], new EscapeGenerator($choices));
        });
        return new self(Generators::oneOf(Generators::constant([]), $escapes));
    }
}
