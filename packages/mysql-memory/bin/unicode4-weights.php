<?php

/**
 * Writes Unicode 4.0 primary weights from the public Default Unicode Collation Element Table.
 *
 * Download https://www.unicode.org/Public/UCA/4.0.0/allkeys-4.0.0.txt separately, then run:
 * php bin/unicode4-weights.php /path/to/allkeys.txt > resources/uca-400-primary.php
 * SQL observations exclude supplementary characters and expansions over eight elements.
 */

declare(strict_types=1);

$source = file_get_contents($argv[1]);
$checksum = 'e97345da79baf2ab6a72304fe84732b5d0c4b4c6adc888679fd17a6a546ec195';
if ($source === false || hash('sha256', $source) !== $checksum) {
    throw new RuntimeException('Expected the original Unicode 4.0 allkeys.txt.');
}
$pages = [];
foreach (explode("\n", $source) as $line) {
    if (preg_match('/^([0-9A-F]+)\s*;\s*([^#]+)/', $line, $entry) !== 1) {
        continue;
    }
    $point = hexdec($entry[1]);
    preg_match_all('/\[[.*]([0-9A-F]+)\.[0-9A-F]+\.[0-9A-F]+\.[0-9A-F]+\]/', $entry[2], $elements, PREG_SET_ORDER);
    if ($point > 0xFFFF || count($elements) > 8) {
        continue;
    }
    $weight = '';
    foreach (array_slice($elements, 0, 8) as $element) {
        if (hexdec($element[1]) !== 0) {
            $weight .= strtolower($element[1]);
        }
    }
    $pages[$point >> 8] ??= array_fill(0, 256, '-');
    $pages[$point >> 8][$point & 255] = $weight;
}
ksort($pages);
$lines = [];
foreach ($pages as $page => $entries) {
    $lines[] = "    $page => '" . implode('|', $entries) . "',";
}
echo "<?php\n\ndeclare(strict_types=1);\n\n/**\n * Weights from the Unicode 4.0 Default Unicode Collation Element Table.\n * Copyright 2001-2003 Unicode, Inc. See unicode-license.txt for permission and terms.\n * Source: https://www.unicode.org/Public/UCA/4.0.0/allkeys-4.0.0.txt\n * Source SHA-256: $checksum\n *\n * Generated by bin/unicode4-weights.php. Each page holds 256 pipe-separated entries.\n * Each entry holds hexadecimal primary weights; a dash is implicit.\n * BMP entries with up to eight collation elements are retained, as observed through SQL.\n */\n\nreturn [\n" . implode("\n", $lines) . "\n];\n";
