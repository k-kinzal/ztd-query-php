<?php

/**
 * Captures public metadata for the installed sys routines without reading their implementation.
 *
 * Neither ROUTINE_DEFINITION nor SHOW CREATE is read. Creation and modification timestamps
 * are omitted because they belong to an installation, rather than to a MySQL release.
 * Source: https://dev.mysql.com/doc/refman/8.4/en/information-schema-routines-table.html,
 * https://dev.mysql.com/doc/refman/8.4/en/information-schema-parameters-table.html.
 * Usage: php bin/system-routines.php <host> <port> <user> <password> > resources/system-routines/mysql-<release>.php
 * Or: php bin/system-routines.php --container=<release> (requires development dependencies and Docker).
 */

declare(strict_types=1);

if (str_starts_with($argv[1], '--container=')) {
    require __DIR__ . '/../vendor/autoload.php';
    $endpoint = Testcontainers\Testcontainers::run(Container\MySqlRelease::container(substr($argv[1], 12)))->getData(Container\Endpoint::class);
    [$host, $port, $user, $password] = [$endpoint->host, $endpoint->port, $endpoint->username, $endpoint->password];
} else {
    [, $host, $port, $user, $password] = $argv;
}
$pdo = new PDO('mysql:host=' . $host . ';port=' . $port . ';charset=utf8mb4', $user, $password, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$fields = 'ROUTINE_NAME, ROUTINE_TYPE, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, CHARACTER_OCTET_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE, DATETIME_PRECISION, CHARACTER_SET_NAME, COLLATION_NAME, DTD_IDENTIFIER, ROUTINE_BODY, EXTERNAL_NAME, EXTERNAL_LANGUAGE, PARAMETER_STYLE, IS_DETERMINISTIC, SQL_DATA_ACCESS, SQL_PATH, SECURITY_TYPE, SQL_MODE, ROUTINE_COMMENT, DEFINER, CHARACTER_SET_CLIENT, COLLATION_CONNECTION, DATABASE_COLLATION';
$parameters = 'SPECIFIC_NAME, ORDINAL_POSITION, PARAMETER_MODE, PARAMETER_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, CHARACTER_OCTET_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE, DATETIME_PRECISION, CHARACTER_SET_NAME, COLLATION_NAME, DTD_IDENTIFIER, ROUTINE_TYPE';
$version = $pdo->query('SELECT @@version')->fetchColumn();
$encode = static fn (mixed $value): string => str_replace('$', '\\$', json_encode($value, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR));
echo "<?php\n\n/**\n * Public sys routine metadata observed on MySQL {$version}; no implementation bodies or installation timestamps.\n *\n * Generated by bin/system-routines.php through INFORMATION_SCHEMA.ROUTINES and PARAMETERS.\n */\n\ndeclare(strict_types=1);\n\nreturn [\n";
foreach (['routines' => [$fields, 'ROUTINES', 'ROUTINE_NAME'], 'parameters' => [$parameters, 'PARAMETERS', 'SPECIFIC_NAME, ORDINAL_POSITION']] as $key => [$columns, $table, $order]) {
    $schema = $key === 'routines' ? 'ROUTINE_SCHEMA' : 'SPECIFIC_SCHEMA';
    $rows = $pdo->query("SELECT {$columns} FROM information_schema.{$table} WHERE {$schema}='sys' ORDER BY ROUTINE_TYPE, {$order}")->fetchAll(PDO::FETCH_NUM);
    echo "    '{$key}' => [\n";
    foreach ($rows as $row) {
        echo '        [' . implode(', ', array_map($encode, $row)) . "],\n";
    }
    echo "    ],\n";
}
echo "];\n";
