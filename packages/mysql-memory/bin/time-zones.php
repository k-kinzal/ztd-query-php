<?php

/**
 * Writes the named time zones of one MySQL release from a running server of that release whose time zone tables were loaded by mysql_tzinfo_to_sql: each name, its number and whether it counts leap seconds.
 *
 * Usage: php bin/time-zones.php <host> <port> <user> <password> > resources/time-zones/mysql-<release>.php
 */

declare(strict_types=1);

$pdo = new PDO('mysql:host=' . $argv[1] . ';port=' . $argv[2], $argv[3], $argv[4], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$zones = [];
foreach ($pdo->query('SELECT n.Name, z.Time_zone_id, z.Use_leap_seconds FROM mysql.time_zone z JOIN mysql.time_zone_name n ON n.Time_zone_id = z.Time_zone_id ORDER BY z.Time_zone_id, n.Name')->fetchAll(PDO::FETCH_NUM) as [$name, $id, $leap]) {
    $zones[] = sprintf('    [%s, %d, %s],', var_export((string) $name, true), (int) $id, $leap === 'Y' ? 'true' : 'false');
}
$version = $pdo->query('SELECT @@version')->fetchColumn();
echo "<?php\n\n/**\n * The named time zones of the time zone tables of a MySQL {$version} server, in the order they are numbered.\n *\n * Each entry: the name mysql.time_zone_name holds, the Time_zone_id it names, and whether mysql.time_zone counts\n * leap seconds for it.\n * Generated by bin/time-zones.php from a server of the release.\n */\n\ndeclare(strict_types=1);\n\nreturn [\n" . implode("\n", $zones) . "\n];\n";
