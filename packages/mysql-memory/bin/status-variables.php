<?php

/**
 * Writes the status variables of one MySQL release from a running server of that release: each name, whether it has a session value, and the value a freshly started server without load shows.
 *
 * Counters are written as 0; the values that describe the configuration of the server are kept, and those that
 * depend on its files, keys or clock are written empty; the redo log is enabled, as on a server no statement disabled it.
 *
 * Usage: php bin/status-variables.php <host> <port> <user> <password> > resources/status/mysql-<release>.php
 */

declare(strict_types=1);

$pdo = new PDO('mysql:host=' . $argv[1] . ';port=' . $argv[2], $argv[3], $argv[4], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$global = [];
foreach ($pdo->query('SHOW GLOBAL STATUS')->fetchAll(PDO::FETCH_NUM) as [$name, $value]) {
    $global[(string) $name] = (string) $value;
}
$session = [];
foreach ($pdo->query('SHOW SESSION STATUS')->fetchAll(PDO::FETCH_NUM) as [$name, $value]) {
    $session[(string) $name] = (string) $value;
}
$scoped = [];
try {
    foreach ($pdo->query('SELECT VARIABLE_NAME FROM performance_schema.status_by_thread WHERE THREAD_ID = PS_CURRENT_THREAD_ID()')->fetchAll(PDO::FETCH_COLUMN) as $name) {
        $scoped[(string) $name] = true;
    }
} catch (PDOException) {
    $scoped = [];
}
$listed = [];
try {
    foreach ([...$pdo->query('SELECT VARIABLE_NAME FROM performance_schema.global_status')->fetchAll(PDO::FETCH_COLUMN), ...$pdo->query('SELECT VARIABLE_NAME FROM performance_schema.session_status')->fetchAll(PDO::FETCH_COLUMN)] as $name) {
        $listed[(string) $name] = true;
    }
} catch (PDOException) {
    $listed = array_fill_keys(array_keys($session + $global), true);
}
$kept = ['Innodb_page_size', 'Innodb_buffer_pool_pages_total', 'Mysqlx_port', 'Ssl_session_cache_size', 'Ssl_session_cache_timeout'];
$blank = '/(rsa_public_key|_not_after|_not_before|Max_used_connections_time|Innodb_buffer_pool_load_status|Current_tls_|Mysqlx_address|Mysqlx_socket|Tls_library_version)/i';
$entries = [];
foreach ($session + $global as $name => $value) {
    $value = $global[$name] ?? $value;
    $value = match (true) {
        $name === 'Innodb_redo_log_enabled' => 'ON',
        in_array($name, $kept, true) => $value,
        is_numeric($value) => '0',
        preg_match($blank, $name) === 1 => '',
        default => $value,
    };
    $scope = !isset($global[$name]) ? 'Session' : (isset($scoped[$name]) ? 'Both' : 'Global');
    $entries[] = sprintf('    [%s, %s, %s, %s],', var_export($name, true), var_export($scope, true), var_export($value, true), isset($listed[$name]) ? 'true' : 'false');
}
$version = $pdo->query('SELECT @@version')->fetchColumn();
echo "<?php\n\n/**\n * The status variables of MySQL {$version}, in the order SHOW STATUS lists them.\n *\n * Each entry: name; Global, Session or Both for the scopes that have a value of it; the global value a freshly started\n * server without load shows: 0 for a counter;\n * whether the status variable tables of the Performance Schema list it.\n * Generated by bin/status-variables.php from a server of the release.\n */\n\ndeclare(strict_types=1);\n\nreturn [\n" . implode("\n", $entries) . "\n];\n";
