<?php

/**
 * Writes Unicode 9.0 collation levels from the public Default Unicode Collation Element Table.
 *
 * Download https://www.unicode.org/Public/UCA/9.0.0/allkeys.txt separately, then run:
 * php bin/unicode-weights.php /path/to/allkeys.txt > resources/uca-900-weights.php
 * SQL observations retain eight elements per character and do not combine contractions.
 */

declare(strict_types=1);

$source = file_get_contents($argv[1]);
$checksum = '0633f4520c99f249b0c53aa1442cd2521702041fb00a32df944fec13c9da3ed5';
if ($source === false || hash('sha256', $source) !== $checksum) {
    throw new RuntimeException('Expected the original Unicode 9.0 allkeys.txt.');
}
$pages = [];
foreach (explode("\n", $source) as $line) {
    if (preg_match('/^([0-9A-F]+)\s*;\s*([^#]+)/', $line, $entry) !== 1) {
        continue;
    }
    $point = hexdec($entry[1]);
    preg_match_all('/\[[.*]([0-9A-F]+)\.([0-9A-F]+)\.([0-9A-F]+)\]/', $entry[2], $elements, PREG_SET_ORDER);
    $levels = ['', '', ''];
    foreach (array_slice($elements, 0, 8) as $element) {
        foreach ($levels as $level => $_) {
            if (hexdec($element[$level + 1]) !== 0) {
                $levels[$level] .= strtolower($element[$level + 1]);
            }
        }
    }
    $pages[$point >> 8] ??= array_fill(0, 256, '-');
    $pages[$point >> 8][$point & 255] = implode(':', $levels);
}
ksort($pages);
$lines = [];
foreach ($pages as $page => $entries) {
    $lines[] = "    $page => '" . implode('|', $entries) . "',";
}
echo "<?php\n\ndeclare(strict_types=1);\n\n/**\n * Weights from the Unicode 9.0 Default Unicode Collation Element Table.\n * Copyright 2016 Unicode, Inc. See unicode-license.txt for permission and terms.\n * Source: https://www.unicode.org/Public/UCA/9.0.0/allkeys.txt\n * Source SHA-256: $checksum\n *\n * Generated by bin/unicode-weights.php. Each page holds 256 pipe-separated entries.\n * An entry has primary:secondary:tertiary hexadecimal weights; a dash is implicit.\n * Single-code-point entries retain eight collation elements, as observed through SQL.\n */\n\nreturn [\n" . implode("\n", $lines) . "\n];\n";
