<?php

/**
 * Writes Unicode 5.2 primary weights from the public Default Unicode Collation Element Table.
 *
 * Download https://www.unicode.org/Public/UCA/5.2.0/allkeys.txt separately, then run:
 * php bin/unicode52-weights.php /path/to/allkeys.txt > resources/uca-520-primary.php
 * SQL observations retain eight elements per character and do not combine contractions.
 */

declare(strict_types=1);

$source = file_get_contents($argv[1]);
$checksum = '47744eece32cf295185a8542f91800f08db7609ca044dc7f6564228c942939fc';
if ($source === false || hash('sha256', $source) !== $checksum) {
    throw new RuntimeException('Expected the original Unicode 5.2 allkeys.txt.');
}
$pages = [];
foreach (explode("\n", $source) as $line) {
    if (preg_match('/^([0-9A-F]+)\s*;\s*([^#]+)/', $line, $entry) !== 1) {
        continue;
    }
    $point = hexdec($entry[1]);
    preg_match_all('/\[[.*]([0-9A-F]+)\.[0-9A-F]+\.[0-9A-F]+\.[0-9A-F]+\]/', $entry[2], $elements, PREG_SET_ORDER);
    $weight = '';
    foreach (array_slice($elements, 0, 8) as $element) {
        if (hexdec($element[1]) !== 0) {
            $weight .= strtolower($element[1]);
        }
    }
    $pages[$point >> 8] ??= array_fill(0, 256, '-');
    $pages[$point >> 8][$point & 255] = $weight;
}
ksort($pages);
$lines = [];
foreach ($pages as $page => $entries) {
    $lines[] = "    $page => '" . implode('|', $entries) . "',";
}
echo "<?php\n\ndeclare(strict_types=1);\n\n/**\n * Weights from the Unicode 5.2 Default Unicode Collation Element Table.\n * Copyright 2001-2009 Unicode, Inc. See unicode-license.txt for permission and terms.\n * Source: https://www.unicode.org/Public/UCA/5.2.0/allkeys.txt\n * Source SHA-256: $checksum\n *\n * Generated by bin/unicode52-weights.php. Each page holds 256 pipe-separated entries.\n * Each entry holds hexadecimal primary weights; a dash is implicit.\n * Single-code-point entries retain eight collation elements, as observed through SQL.\n */\n\nreturn [\n" . implode("\n", $lines) . "\n];\n";
