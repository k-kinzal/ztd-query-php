<?php

/**
 * Writes the system variable catalog of one MySQL release from a running server of that release.
 *
 * Usage: php bin/variables.php <dsn> <user> <password> > resources/variables/mysql-<release>.php
 * Run it against a disposable server: assignments of each variable to its own value are made to
 * learn which variables are read-only.
 */

declare(strict_types=1);

$pdo = new PDO($argv[1], $argv[2], $argv[3], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$rows = $pdo->query('SELECT v.VARIABLE_NAME, v.VARIABLE_VALUE, i.MIN_VALUE, i.MAX_VALUE FROM (SELECT VARIABLE_NAME, VARIABLE_VALUE FROM performance_schema.global_variables UNION SELECT s.VARIABLE_NAME, s.VARIABLE_VALUE FROM performance_schema.session_variables s WHERE s.VARIABLE_NAME NOT IN (SELECT VARIABLE_NAME FROM performance_schema.global_variables)) v LEFT JOIN performance_schema.variables_info i ON i.VARIABLE_NAME = v.VARIABLE_NAME ORDER BY v.VARIABLE_NAME')->fetchAll(PDO::FETCH_NUM);
$entries = [];
foreach ($rows as [$name, $value, $minimum, $maximum]) {
    $name = strtolower((string) $name);
    $session = true;
    try {
        $pdo->query("SELECT @@SESSION.`$name`")->fetchAll();
    } catch (PDOException $failure) {
        $session = false;
    }
    $global = true;
    try {
        $pdo->query("SELECT @@GLOBAL.`$name`")->fetchAll();
    } catch (PDOException $failure) {
        $global = false;
    }
    $readOnly = false;
    try {
        $pdo->exec($session ? "SET @@SESSION.`$name` = @@SESSION.`$name`" : "SET @@GLOBAL.`$name` = @@GLOBAL.`$name`");
    } catch (PDOException $failure) {
        $readOnly = in_array((int) ($failure->errorInfo[1] ?? 0), [1238, 1621], true);
    }
    $value = (string) $value;
    $shape = match (true) {
        in_array($value, ['ON', 'OFF'], true) => 'Boolean',
        $minimum !== null && $maximum !== null && $maximum !== '0' && preg_match('/\A-?[0-9]+\z/', $value) === 1 => str_starts_with((string) $minimum, '-') ? 'Integer' : 'Unsigned',
        preg_match('/\A[0-9]+\.[0-9]+\z/', $value) === 1 && $maximum !== null && $maximum !== '0' => 'Double',
        default => 'Text',
    };
    $scope = $session && $global ? 'Both' : ($session ? 'Session' : 'Global');
    $default = in_array($shape, ['Integer', 'Unsigned'], true) ? (int) $value : $value;
    $entries[] = sprintf("    [%s, '%s', '%s', %s, %s, %s, %s],", var_export($name, true), $scope, $shape, var_export($default, true), $readOnly ? 'true' : 'false', $shape === 'Text' || $shape === 'Boolean' || $shape === 'Double' || $minimum === null ? 'null' : ($minimum === '-9223372036854775808' ? 'PHP_INT_MIN' : $minimum), $shape === 'Text' || $shape === 'Boolean' || $shape === 'Double' || $maximum === null ? 'null' : (bccomp((string) $maximum, (string) PHP_INT_MAX) > 0 ? 'PHP_INT_MAX' : $maximum));
}
$version = $pdo->query('SELECT @@version')->fetchColumn();
echo "<?php\n\n/**\n * The system variables of MySQL {$version}: name, scope, values, global default, whether read-only, and integer bounds.\n *\n * Generated by bin/variables.php from a server of the release.\n */\n\ndeclare(strict_types=1);\n\nreturn [\n" . implode("\n", $entries) . "\n];\n";
