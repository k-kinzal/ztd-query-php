<?php

/**
 * Writes the plugins, keywords and storage engines INFORMATION_SCHEMA lists on a server of one MySQL release, from a running server of that release without extra plugins.
 *
 * Usage: php bin/server-tables.php <host> <port> <user> <password> > resources/server-tables/mysql-<release>.php
 */

declare(strict_types=1);

$pdo = new PDO('mysql:host=' . $argv[1] . ';port=' . $argv[2], $argv[3], $argv[4], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$plugins = [];
foreach ($pdo->query('SELECT PLUGIN_NAME, PLUGIN_VERSION, PLUGIN_STATUS, PLUGIN_TYPE, PLUGIN_TYPE_VERSION, PLUGIN_LIBRARY, PLUGIN_LIBRARY_VERSION, PLUGIN_AUTHOR, PLUGIN_DESCRIPTION, PLUGIN_LICENSE, LOAD_OPTION FROM information_schema.PLUGINS')->fetchAll(PDO::FETCH_NUM) as $row) {
    $plugins[] = '        [' . implode(', ', array_map(static fn (mixed $value): string => var_export($value, true), $row)) . '],';
}
$engines = [];
foreach ($pdo->query('SELECT ENGINE, SUPPORT, COMMENT, TRANSACTIONS, XA, SAVEPOINTS FROM information_schema.ENGINES')->fetchAll(PDO::FETCH_NUM) as $row) {
    $engines[] = '        [' . implode(', ', array_map(static fn (mixed $value): string => var_export($value, true), $row)) . '],';
}
$keywords = [];
$listed = (int) $pdo->query("SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA = 'information_schema' AND TABLE_NAME = 'KEYWORDS'")->fetchColumn() > 0;
foreach ($listed ? $pdo->query('SELECT WORD, RESERVED FROM information_schema.KEYWORDS')->fetchAll(PDO::FETCH_NUM) : [] as [$word, $reserved]) {
    $keywords[] = '        [' . var_export((string) $word, true) . ', ' . (int) $reserved . '],';
}
$version = $pdo->query('SELECT @@version')->fetchColumn();
echo "<?php\n\n/**\n * The plugins, keywords and storage engines INFORMATION_SCHEMA lists on a MySQL {$version} server.\n *\n * Plugins: name, version, status, type, type version, library, library version, author, description, license,\n * load option. Keywords: word, whether it is reserved. Engines: name, support, comment, transactions, XA, savepoints.\n * Generated by bin/server-tables.php from a server of the release.\n */\n\ndeclare(strict_types=1);\n\nreturn [\n    'plugins' => [\n" . implode("\n", $plugins) . "\n    ],\n    'keywords' => [\n" . implode("\n", $keywords) . "\n    ],\n    'engines' => [\n" . implode("\n", $engines) . "\n    ],\n];\n";
