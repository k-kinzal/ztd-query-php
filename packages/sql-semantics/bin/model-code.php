declare(strict_types=1);

/**
 * The terminals and terminal classes whose text is a name, which `.` follows directly and `(` does not.
 *
 * A keyword used as a name is one too, except in MySQL, whose lexer reads a
 * word followed directly by `.` as an identifier rather than a keyword.
 */
const IDENTIFIER_SYMBOLS = ['IDENT', 'IDENT_QUOTED', 'ID', 'UIDENT', 'id', 'ids', 'idj', 'nm'];

/**
 * Turns a grammar label into a PHP name, without storing that label in a value.
 */
function modelName(string $name): string
{
    $name = preg_replace('/([a-z0-9])([A-Z])/', '$1 $2', $name) ?? $name;
    $name = preg_replace('/([A-Z])([A-Z][a-z])/', '$1 $2', $name) ?? $name;

    return str_replace(' ', '', ucwords(strtolower(preg_replace('/[^a-zA-Z0-9]+/', ' ', $name) ?? '')));
}

/**
 * Gives common SQL arguments their semantic names.
 */
function fieldName(string $name): string
{
    return [
        'select_item_list' => 'projections', 'opt_target_list' => 'projections', 'target_list' => 'projections', 'selcollist' => 'projections',
        'opt_from_clause' => 'from', 'from_clause' => 'from', 'where_clause' => 'where', 'opt_where_clause' => 'where', 'where_opt' => 'where',
        'group_clause' => 'groupBy', 'groupby_opt' => 'groupBy', 'having_clause' => 'having', 'having_opt' => 'having',
        'orderby_opt' => 'orderBy', 'order_clause' => 'orderBy', 'opt_order_clause' => 'orderBy', 'sort_clause' => 'orderBy',
        'limit_opt' => 'pagination', 'select_options' => 'options', 'query_expression' => 'query', 'query_specification' => 'query',
        'with_clause' => 'with', 'opt_with_clause' => 'with', 'distinct_clause' => 'distinct',
        'IDENT' => 'name', 'IDENT_QUOTED' => 'name', 'ID' => 'name', 'SCONST' => 'value', 'TEXT_STRING' => 'value', 'STRING' => 'value',
        'NUM' => 'value', 'INTEGER' => 'value', 'ICONST' => 'value', 'FCONST' => 'value', 'FLOAT' => 'value',
    ][$name] ?? lcfirst(modelName($name));
}

/**
 * Writes a generated definition below the model's own autoload root.
 */
function writeModel(string $directory, string $dialect, string $group, string $name, string $body): string
{
    $namespace = 'SqlSemantics\\Statement\\Model\\' . $dialect . '\\' . $group;
    $path = $directory . '/models/' . $group;
    if (!is_dir($path)) {
        mkdir($path, 0777, true);
    }
    file_put_contents($path . '/' . $name . '.php', "<?php\n\ndeclare(strict_types=1);\n\nnamespace {$namespace};\n\n{$body}\n");

    return $namespace . '\\' . $name;
}

/**
 * Documents the generated public type and its parser-free construction contract.
 */
function modelDoc(string $name, string $fqcn): string
{
    return "/**\n * The {$name} SQL value; generated by bin/build-models.php.\n *\n * @visibility public\n * @example Accept a structured SQL value\n *     \$write = static fn (\\{$fqcn} \$value): string => \\SqlSemantics\\Statement\\Writer::render(\$value);\n *     \$write instanceof \\Closure // => true\n */\n";
}

/**
 * Supplies the rule's role and every role that transparently forwards it.
 *
 * @param array<string, list<string>> $parents
 * @param list<string> $entryRules
 * @return list<string>
 */
function roles(string $name, string $dialect, array $parents, array $entryRules = []): array
{
    $seen = [];
    $pending = [$name];
    while ($pending !== []) {
        $next = array_pop($pending);
        if (isset($seen[$next])) {
            continue;
        }
        $seen[$next] = true;
        array_push($pending, ...($parents[$next] ?? []));
    }
    $names = array_keys($seen);
    sort($names);

    $roles = array_values(array_unique(array_map(static fn (string $role): string => '\\SqlSemantics\\Statement\\Model\\' . $dialect . '\\Role\\' . modelName($role) . 'Form', $names)));
    $roots = match ($dialect) {
        'MySql' => ['start_entry', 'sql_statement', 'simple_statement_or_begin', 'query', 'verb_clause', 'statement'],
        'PostgreSql' => ['parse_toplevel', 'stmtmulti', 'toplevel_stmt', 'stmt'],
        'Sqlite' => ['input', 'cmdlist', 'ecmd', 'cmdx', 'cmd'],
    };
    if (array_intersect($names, [...$roots, ...$entryRules]) !== []) {
        $roles[] = '\\SqlSemantics\\Statement\\Command';
    }

    return $roles;
}

/**
 * Emits a class with named, typed arguments and fixed SQL in its writer.
 *
 * Every symbol position writes its comments first. A fixed `@` is a prefix that
 * the following value must touch, so the writer never separates them.
 *
 * @param list<array{name: string, terminal: bool, fixed: ?string, identifier?: bool}> $symbols
 * @param list<string> $roles
 * @return array{class: class-string, fields: list<int>}
 */
function valueClass(string $directory, string $dialect, string $rule, array $symbols, array $roles, array $bindings = []): array
{
    foreach ($symbols as $symbol) {
        if (str_starts_with($symbol['name'], 'GRAMMAR_SELECTOR_') || str_starts_with($symbol['name'], 'MODE_')) {
            $roles = array_values(array_diff($roles, ['\\SqlSemantics\\Statement\\Command']));
        }
    }
    $name = valueName($rule, $symbols);
    $fqcn = 'SqlSemantics\\Statement\\Model\\' . $dialect . '\\Value\\' . $name;
    $parameters = [];
    $writes = [];
    $fields = [];
    $counts = [];
    $types = [];
    $assertions = [];
    $children = [];
    $contract = '\\SqlSemantics\\Statement\\Model\\' . $dialect . '\\Contract\\Contracts';
    $comments = '\\SqlSemantics\\Statement\\Comments';
    foreach ($symbols as $index => $symbol) {
        $writes[] = "        \$writer->comments(\$this->comments, {$index});";
        if ($symbol['fixed'] !== null) {
            if ($symbol['fixed'] !== '') {
                $writes[] = '        $writer->append(' . var_export($symbol['fixed'], true) . ($symbol['fixed'] === '@' ? ', prefix: true' : '') . ');';
            }
            continue;
        }
        $field = ($symbol['identifier'] ?? false) ? 'name' : fieldName($symbol['name']);
        $counts[$field] = ($counts[$field] ?? 0) + 1;
        $field .= $counts[$field] === 1 ? '' : $counts[$field];
        $type = $symbol['terminal'] ? 'string' : '\\SqlSemantics\\Statement\\Model\\' . $dialect . '\\Role\\' . modelName($symbol['name']) . 'Form';
        $parameters[] = "        public readonly {$type} \${$field},";
        $types[$field] = $type;
        $assertions[] = $symbol['terminal']
            ? "        \$this->assertMatchesPattern(\${$field}, {$contract}::SPELLINGS[" . var_export($symbol['name'], true) . '], ' . var_export('The ' . $field . ' must be a complete ' . $symbol['name'] . ' lexical spelling.', true) . ');'
            : "        \$this->assert({$contract}::contains(\${$field}), 'The {$field} must be a generated immutable SQL value.');";
        $minimums = [];
        foreach ($bindings[$name] ?? [] as $version => $binding) {
            if (isset($binding['operands'][$index])) {
                $minimums[$version] = $binding['operands'][$index];
            }
        }
        if ($minimums !== []) {
            $assertions[] = "        \$this->assertOperandBindingStrength(\${$field}, {$contract}::BINDING_POWERS, " . str_replace("\n", '', var_export($minimums, true)) . ", {$contract}::BINDING_RULES, " . var_export($symbol['name'], true) . ');';
        }
        $identifier = in_array($symbol['name'], IDENTIFIER_SYMBOLS, true) || ($dialect !== 'MySql' && ($symbol['identifier'] ?? false)) ? ', true' : '';
        $writes[] = $symbol['terminal'] ? "        \$writer->append(\$this->{$field}{$identifier});" : "        \$this->{$field}->write(\$writer);";
        if (!$symbol['terminal']) {
            $children[$field] = $type;
        }
        $fields[] = $index;
    }
    $parameters[] = "        public readonly {$comments} \$comments = new {$comments}(),";
    $types['comments'] = $comments;
    $constructor = ($assertions === [] && $children === [] ? '' : "    use \\SqlSemantics\\Statement\\Assertion;\n\n") . "    /**\n     * Supplies the SQL values of this form; comments are kept by the position of the symbol each precedes.\n     */\n    public function __construct(\n" . implode("\n", $parameters) . "\n    ) {\n" . ($assertions === [] ? '' : implode("\n", $assertions) . "\n") . "    }\n\n";
    $body = modelDoc($rule, $fqcn) . "final class {$name} implements " . implode(', ', $roles) . "\n{\n{$constructor}    /**\n     * Writes SQL entirely from this value's fields.\n     */\n    public function write(\\SqlSemantics\\Statement\\Writer \$writer): void\n    {\n" . implode("\n", $writes) . "\n    }" . traversalMethods($types, $children) . copyMethods($types) . "\n}";
    writeModel($directory, $dialect, 'Value', $name, $body);

    return ['class' => $fqcn, 'fields' => $fields];
}

/**
 * Keeps the existing public class identity independent of generated assertions.
 *
 * @param list<array{name: string, terminal: bool, fixed: ?string, identifier?: bool}> $symbols
 */
function valueName(string $rule, array $symbols): string
{
    $signature = json_encode([$rule, $symbols], JSON_THROW_ON_ERROR);
    $label = implode(' ', array_column($symbols, 'name'));

    return modelName($rule) . 'With' . substr(modelName($label), 0, 75) . '_' . substr(hash('sha256', $signature), 0, 8);
}

/**
 * Replaces finite SQL choices, including absent clauses, with enums.
 *
 * @param array<int, string> $choices
 * @param list<string> $roles
 * @return array<int, array{constant: string}>
 */
function choiceEnum(string $directory, string $dialect, string $rule, array $choices, array $roles, array $alternatives = []): array
{
    $name = modelName($rule) . 'Choice_' . substr(hash('sha256', json_encode($choices, JSON_THROW_ON_ERROR)), 0, 8);
    $fqcn = 'SqlSemantics\\Statement\\Model\\' . $dialect . '\\Choice\\' . $name;
    $cases = [];
    $mapping = [];
    foreach ($choices as $ordinal => $sql) {
        if (in_array('@', explode(' ', $sql), true)) {
            throw new RuntimeException('A fixed @ must be written as a prefix, which a choice cannot express: ' . $rule);
        }
        $case = 'Use' . substr(modelName($sql), 0, 80) . '_' . substr(hash('sha256', $sql), 0, 8);
        $cases[$case] = '    case ' . $case . ' = ' . var_export($sql, true) . ';';
        $mapping[$ordinal] = ['constant' => $fqcn . '::' . $case, 'symbols' => array_column($alternatives[$ordinal] ?? [], 'name')];
    }
    $body = modelDoc($rule, $fqcn) . "enum {$name}: string implements " . implode(', ', $roles) . "\n{\n" . implode("\n", $cases) . "\n\n    /**\n     * Writes the selected SQL option.\n     */\n    public function write(\\SqlSemantics\\Statement\\Writer \$writer): void\n    {\n        foreach (explode(' ', \$this->value) as \$word) {\n            \$writer->append(\$word);\n        }\n    }\n\n    /**\n     * A choice is made of no values.\n     *\n     * @return list<\\SqlSemantics\\Statement\\Element>\n     */\n    public function children(): array\n    {\n        return [];\n    }\n\n    /**\n     * A choice has nothing to replace.\n     *\n     * @param callable(\\SqlSemantics\\Statement\\Element): \\SqlSemantics\\Statement\\Element \$replace\n     */\n    public function map(callable \$replace): static\n    {\n        return \$this;\n    }\n}";
    writeModel($directory, $dialect, 'Choice', $name, $body);

    return $mapping;
}

/**
 * Lists the managed PHP resources, relative to their root, in stable order.
 *
 * @return array<string, string>
 */
function resourceFiles(string $directory): array
{
    $files = [];
    foreach (['models', 'mapping'] as $group) {
        if (!is_dir($directory . '/' . $group)) {
            continue;
        }
        $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($directory . '/' . $group, FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            if ($file->isFile() && $file->getExtension() === 'php') {
                $files[substr($file->getPathname(), strlen($directory) + 1)] = $file->getPathname();
            }
        }
    }
    ksort($files);

    return $files;
}

/**
 * Compares or installs the whole vocabulary, detecting obsolete and new files.
 */
function publishModels(string $directory, string $destination, bool $check): int
{
    $generated = resourceFiles($directory);
    $existing = resourceFiles($destination);
    $changes = 0;
    foreach ($generated as $relative => $path) {
        $target = $destination . '/' . $relative;
        if (isset($existing[$relative]) && hash_file('sha256', $path) === hash_file('sha256', $target)) {
            continue;
        }
        ++$changes;
        if (!$check) {
            if (!is_dir(dirname($target))) {
                mkdir(dirname($target), 0777, true);
            }
            copy($path, $target);
        }
    }
    foreach (array_diff_key($existing, $generated) as $path) {
        ++$changes;
        if (!$check) {
            unlink($path);
        }
    }
    fwrite(STDOUT, count($generated) . " resources; {$changes} " . ($check ? 'differences' : 'updates') . "\n");

    return $check && $changes !== 0 ? 1 : 0;
}

/**
 * Generates the child listing and the rebuilding map of a value class.
 *
 * @param array<string, string> $types Every field and its type, the comments last
 * @param array<string, string> $children The fields that hold values and their role types
 */
function traversalMethods(array $types, array $children): string
{
    $element = '\\SqlSemantics\\Statement\\Element';
    $list = implode(', ', array_map(static fn (string $field): string => '$this->' . $field, array_keys($children)));
    $methods = "\n\n    /**\n     * Lists the values of this form, in writing order.\n     *\n     * @return list<{$element}>\n     */\n    public function children(): array\n    {\n        return [{$list}];\n    }";
    if ($children === []) {
        return $methods . "\n\n    /**\n     * This form holds no values to replace.\n     *\n     * @param callable({$element}): {$element} \$replace\n     */\n    public function map(callable \$replace): static\n    {\n        return \$this;\n    }";
    }
    $arguments = [];
    foreach ($types as $field => $type) {
        $arguments[] = isset($children[$field]) ? "\$this->replacement(\$this->{$field}, {$type}::class, \$replace)" : '$this->' . $field;
    }

    return $methods . "\n\n    /**\n     * Returns a copy whose values are replaced by what the function answers for each, keeping lexical fields and comments.\n     *\n     * @param callable({$element}): {$element} \$replace\n     */\n    public function map(callable \$replace): static\n    {\n        return new self(" . implode(', ', $arguments) . ");\n    }";
}
