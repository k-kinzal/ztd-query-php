#[\PHPUnit\Framework\Attributes\UsesClass(\SqlSemantics\Platform\PostgreSql\NameRules::class)]
#[\PHPUnit\Framework\Attributes\UsesClass(\SqlSemantics\Platform\PostgreSql\SchemaRules::class)]
#[\PHPUnit\Framework\Attributes\UsesClass(\SqlSemantics\Platform\Sqlite\Platform::class)]
#[\PHPUnit\Framework\Attributes\UsesClass(\SqlSemantics\Platform\Sqlite\TypeRules::class)]
#[\PHPUnit\Framework\Attributes\UsesClass(\SqlSemantics\Platform\Sqlite\NameRules::class)]
#[\PHPUnit\Framework\Attributes\UsesClass(\SqlSemantics\Platform\Sqlite\SchemaRules::class)]
#[\PHPUnit\Framework\Attributes\UsesClass(\SqlSemantics\Platform\MySql\Platform::class)]
#[\PHPUnit\Framework\Attributes\UsesClass(\SqlSemantics\Platform\MySql\TypeRules::class)]
#[\PHPUnit\Framework\Attributes\UsesClass(\SqlSemantics\Platform\MySql\NameRules::class)]
#[\PHPUnit\Framework\Attributes\UsesClass(\SqlSemantics\Platform\MySql\SchemaRules::class)]
#[Medium]
#[CoversClass(\SqlSemantics\Core\Analysis\ValueReader::class)]
#[CoversClass(\SqlSemantics\Core\Ast\ColumnProperties::class)]
#[CoversClass(\SqlSemantics\Statement\Declaration\ColumnGeneration::class)]
#[CoversClass(\SqlSemantics\Statement\Declaration\Invariant::class)]
#[CoversClass(\SqlSemantics\Statement\ImmutableGraph::class)]
#[CoversClass(Writer::class)]
#[CoversClass(\SqlSemantics\Statement\Assertion::class)]
final class ColumnPropertiesTest extends TestCase
{
    public function testGenerationDoesNotConfuseDefaultCastsWithGeneratedColumns(): void
    {
        $state = Resolved::of((new Semantics(PostgreSqlDialect::PostgreSql))->analyze('CREATE TABLE t (id INT DEFAULT CAST(1 AS INT))', []));
        self::assertNull($state->declarations[0]->columns[0]->generation);
        self::assertNotNull($state->declarations[0]->columns[0]->defaultExpression);
    }

    public function testGenerationPreservesVirtualAndIdentityKinds(): void
    {
        $state = Resolved::of((new Semantics(SqliteDialect::Sqlite))->analyze('CREATE TABLE t (stored INT, x INT AS (stored + 1) VIRTUAL)', []));
        self::assertSame('virtual', $state->declarations[0]->columns[1]->generation?->kind->value);
        $identity = Resolved::of((new Semantics(PostgreSqlDialect::PostgreSql))->analyze('CREATE TABLE t (id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 10))', []))->declarations[0]->columns[0];
        self::assertSame('identity', $identity->generation?->kind->value);
        self::assertNull($identity->generation->expression);
    }

    public function testCollationKeepsQuotedNames(): void
    {
        $column = Resolved::of((new Semantics(PostgreSqlDialect::PostgreSql))->analyze('CREATE TABLE t (label TEXT COLLATE "C")', []))->declarations[0]->columns[0];
        self::assertNotNull($column->collation);
        self::assertSame('COLLATE "C"', Writer::render($column->collation));
    }

    public function testAutoIncrementIsAnExplicitStateProperty(): void
    {
        $state = Resolved::of((new Semantics(MySqlDialect::MySql))->analyze('CREATE TABLE t (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, note TEXT)', []));
        self::assertTrue($state->declarations[0]->columns[0]->autoIncrement);
        self::assertFalse($state->declarations[0]->columns[1]->autoIncrement);
        self::assertSame(\SqlSemantics\Statement\Declaration\Builtin::BigInt, $state->declarations[0]->columns[0]->type->name);
        self::assertTrue($state->declarations[0]->columns[0]->type->unsigned);
    }


    public function testGenerationKeepsNestedQueryStructureInsideTheColumn(): void
    {
        $state = Resolved::of((new Semantics(MySqlDialect::MySql))->analyze('CREATE TABLE t (id INT AS ((SELECT 1)))', []));
        self::assertSame(['id'], array_column($state->declarations[0]->columns, 'name'));
        self::assertNotNull($state->declarations[0]->columns[0]->generation);
        self::assertNotNull($state->declarations[0]->columns[0]->generation->expression);
        self::assertStringContainsString('SELECT 1', Writer::render($state->declarations[0]->columns[0]->generation->expression));
    }

    public function testGenerationDoesNotTreatNamedDefaultsAsComputedColumns(): void
    {
        $column = Resolved::of((new Semantics(PostgreSqlDialect::PostgreSql))->analyze('CREATE TABLE t (id INT CONSTRAINT d DEFAULT CAST(1 AS INT))', []))->declarations[0]->columns[0];
        self::assertNull($column->generation);
        self::assertNotNull($column->defaultExpression);
    }

    public function testAutoIncrementDoesNotInspectDefaultExpressionIdentifiers(): void
    {
        $column = Resolved::of((new Semantics(PostgreSqlDialect::PostgreSql))->analyze('CREATE TABLE t (id INT DEFAULT auto_increment())', []))->declarations[0]->columns[0];
        self::assertFalse($column->autoIncrement);
        self::assertSame(\SqlSemantics\Statement\Declaration\Nullability::MaybeNull, $column->nullability);
    }

}
