<?php

declare(strict_types=1);

namespace Tests\Unit\Serialization\Definition\Relation;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Medium;
use PHPUnit\Framework\Attributes\TestWith;
use PHPUnit\Framework\TestCase;
use SqlSemantics\Binder;
use SqlSemantics\Dialect;
use SqlSemantics\Model\Definition\Relation;
use SqlSemantics\Model\Statement\Definition\PostgreSql\Relation\AlterRelationStatement;
use SqlSemantics\SchemaBuilder;
use SqlSemantics\Serialization\Definition\Relation\IdentityActions;

#[CoversClass(IdentityActions::class)]
#[Medium]
final class IdentityActionsTest extends TestCase
{
    public function testWriteWritesAdditionsChangesAndRemovals(): void
    {
        $statement = (new Binder((new SchemaBuilder(Dialect::PostgreSql))->build('CREATE TABLE t(id INTEGER)')))->bind('ALTER TABLE t ALTER id DROP IDENTITY IF EXISTS');
        self::assertInstanceOf(AlterRelationStatement::class, $statement);
        self::assertInstanceOf(Relation\Identity\DropColumnIdentity::class, $statement->actions[0]);
        self::assertSame('DROP IDENTITY IF EXISTS', implode(' ', array_map(static fn ($tree): string => $tree->toString(), IdentityActions::write($statement->actions[0]))));
    }

    #[TestWith([\SqlSemantics\Schema\Column\IdentityMode::Always, 'ALWAYS'])]
    #[TestWith([\SqlSemantics\Schema\Column\IdentityMode::ByDefault, 'BY DEFAULT'])]
    public function testModeSpellsTheGenerationMode(\SqlSemantics\Schema\Column\IdentityMode $mode, string $expected): void
    {
        self::assertSame($expected, IdentityActions::mode($mode));
    }

    public function testOptionWritesEachSequenceOption(): void
    {
        self::assertSame('NO CYCLE', IdentityActions::option(Relation\Identity\SequenceFlag::NoCycle)->toString());
        self::assertSame('OWNED BY NONE', IdentityActions::option(new Relation\Identity\SetSequenceOwner(null))->toString());
        self::assertSame('RESTART', IdentityActions::option(new Relation\Identity\RestartIdentity(null))->toString());
    }

    #[TestWith(['ALTER TABLE t ALTER id ADD GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 2 NO CYCLE SEQUENCE NAME s AS bigint MAXVALUE 9 RESTART WITH 3)', 'ALTER TABLE "t" ALTER COLUMN "id" ADD GENERATED ALWAYS AS IDENTITY(START WITH 1 INCREMENT BY 2 NO CYCLE SEQUENCE NAME "s" AS bigint MAXVALUE 9 RESTART WITH 3)'])]
    #[TestWith(['ALTER TABLE t ALTER id ADD GENERATED BY DEFAULT AS IDENTITY', 'ALTER TABLE "t" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY'])]
    #[TestWith(['ALTER TABLE t ALTER id ADD GENERATED ALWAYS AS IDENTITY (OWNED BY t.id)', 'ALTER TABLE "t" ALTER COLUMN "id" ADD GENERATED ALWAYS AS IDENTITY(OWNED BY "t"."id")'])]
    #[TestWith(['ALTER TABLE t ALTER id SET GENERATED BY DEFAULT SET INCREMENT BY 2 RESTART WITH 5 SET NO CYCLE RESTART SET SEQUENCE NAME x SET START 4', 'ALTER TABLE "t" ALTER COLUMN "id" SET GENERATED BY DEFAULT SET INCREMENT BY 2 RESTART WITH 5 SET NO CYCLE RESTART SET SEQUENCE NAME "x" SET START WITH 4'])]
    #[TestWith(['ALTER TABLE t ALTER id SET GENERATED ALWAYS', 'ALTER TABLE "t" ALTER COLUMN "id" SET GENERATED ALWAYS'])]
    #[TestWith(['ALTER TABLE t ALTER id DROP IDENTITY', 'ALTER TABLE "t" ALTER COLUMN "id" DROP IDENTITY'])]
    public function testWriteSpellsEveryIdentityAction(string $sql, string $expected): void
    {
        self::assertSame($expected, (new \SqlSemantics\SimpleSerializer())->serialize((new Binder((new SchemaBuilder(Dialect::PostgreSql))->build('CREATE TABLE t(id INTEGER)')))->bind($sql)));
    }

    public function testOptionWritesValueStorageNameAndOwner(): void
    {
        $statement = (new Binder((new SchemaBuilder(Dialect::PostgreSql))->build('CREATE TABLE t(id INTEGER)')))->bind('ALTER TABLE t ALTER id ADD GENERATED ALWAYS AS IDENTITY (INCREMENT BY 2 SEQUENCE NAME s.q AS bigint OWNED BY t.id RESTART WITH 3)');
        self::assertInstanceOf(AlterRelationStatement::class, $statement);
        self::assertInstanceOf(Relation\Identity\AddColumnIdentity::class, $statement->actions[0]);
        self::assertSame(['INCREMENT BY 2', 'SEQUENCE NAME "s"."q"', 'AS bigint', 'OWNED BY "t"."id"', 'RESTART WITH 3'], array_map(static fn ($option): string => IdentityActions::option($option)->toString(), $statement->actions[0]->options));
    }
}
