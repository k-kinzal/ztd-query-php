<?php

declare(strict_types=1);

namespace Tests\Unit\Serialization\Definition;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Medium;
use PHPUnit\Framework\TestCase;
use SqlSemantics\Binder;
use SqlSemantics\Dialect;
use SqlSemantics\Model\Statement\CreateTableStatement;
use SqlSemantics\Schema\Column\IdentityColumn;
use SqlSemantics\Schema\Column\SequenceOptions;
use SqlSemantics\SchemaBuilder;
use SqlSemantics\Serialization\Definition\Sequence;

#[CoversClass(Sequence::class)]
#[Medium]
final class SequenceTest extends TestCase
{
    public function testWriteSerializesEveryDeclaredAttributeInParentheses(): void
    {
        $binder = new Binder((new SchemaBuilder(Dialect::PostgreSql))->build());
        $statement = $binder->bind('CREATE TABLE t (a INT GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 2 MINVALUE 1 MAXVALUE 100 CACHE 5 CYCLE))');
        self::assertInstanceOf(CreateTableStatement::class, $statement);
        $generation = $statement->definition->table->columns[0]->generation;
        self::assertInstanceOf(IdentityColumn::class, $generation);
        self::assertSame('(START WITH 1 INCREMENT BY 2 MINVALUE 1 MAXVALUE 100 CACHE 5 CYCLE)', Sequence::write($generation->sequence)->toString());
        $rebound = $binder->bind($statement->toString());
        self::assertInstanceOf(CreateTableStatement::class, $rebound);
        $again = $rebound->definition->table->columns[0]->generation;
        self::assertInstanceOf(IdentityColumn::class, $again);
        self::assertTrue($again->sequence->cycle);
        self::assertSame('2', $again->sequence->increment?->spelling());
    }

    public function testWriteLeavesOmittedAttributesToDatabaseDefaults(): void
    {
        $statement = (new Binder((new SchemaBuilder(Dialect::PostgreSql))->build()))->bind('CREATE TABLE t (c INT GENERATED BY DEFAULT AS IDENTITY (NO CYCLE))');
        self::assertInstanceOf(CreateTableStatement::class, $statement);
        $generation = $statement->definition->table->columns[0]->generation;
        self::assertInstanceOf(IdentityColumn::class, $generation);
        self::assertSame('(NO CYCLE)', Sequence::write($generation->sequence)->toString());
        self::assertSame('', Sequence::write(new SequenceOptions())->toString());
    }

    public function testWriteSerializesNameStoragePersistenceOwnerAndRestart(): void
    {
        $binder = new Binder((new SchemaBuilder(Dialect::PostgreSql))->build());
        $statement = $binder->bind('CREATE TABLE t (a INT GENERATED ALWAYS AS IDENTITY (RESTART LOGGED OWNED BY t.a AS smallint SEQUENCE NAME q))');
        self::assertInstanceOf(CreateTableStatement::class, $statement);
        $generation = $statement->definition->table->columns[0]->generation;
        self::assertInstanceOf(IdentityColumn::class, $generation);
        self::assertSame('(SEQUENCE NAME "q" AS smallint LOGGED OWNED BY "t"."a" RESTART)', Sequence::write($generation->sequence)->toString());
        self::assertSame($statement->toString(), $binder->bind($statement->toString())->toString());
    }
}
