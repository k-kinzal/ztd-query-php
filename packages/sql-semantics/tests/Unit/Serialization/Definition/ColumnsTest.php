<?php

declare(strict_types=1);

namespace Tests\Unit\Serialization\Definition;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Medium;
use PHPUnit\Framework\Attributes\TestWith;
use PHPUnit\Framework\TestCase;
use SqlSemantics\Binder;
use SqlSemantics\Dialect;
use SqlSemantics\Model\Statement\CreateTableStatement;
use SqlSemantics\Schema\Column\AutoIncrementColumn;
use SqlSemantics\Schema\Column\ComputedColumn;
use SqlSemantics\Schema\Column\IdentityColumn;
use SqlSemantics\Schema\Column\SuppliedColumn;
use SqlSemantics\SchemaBuilder;
use SqlSemantics\Serialization\Definition\Columns;

#[CoversClass(Columns::class)]
#[Medium]
final class ColumnsTest extends TestCase
{
    /**
     * @param class-string<AutoIncrementColumn|ComputedColumn|IdentityColumn|SuppliedColumn> $generation
     */
    #[TestWith([Dialect::MySql, 'e TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP', '`e` timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP', SuppliedColumn::class])]
    #[TestWith([Dialect::MySql, 'b INT GENERATED ALWAYS AS (a + 1) STORED', '`b` integer GENERATED ALWAYS AS((`a` + 1)) STORED', ComputedColumn::class])]
    #[TestWith([Dialect::MySql, 'c INT AS (a) VIRTUAL', '`c` integer GENERATED ALWAYS AS(`a`) VIRTUAL', ComputedColumn::class])]
    #[TestWith([Dialect::MySql, 'd INT NOT NULL AUTO_INCREMENT', '`d` integer NOT NULL AUTO_INCREMENT', AutoIncrementColumn::class])]
    #[TestWith([Dialect::PostgreSql, 'i INT GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 2 MINVALUE 1 MAXVALUE 100 CACHE 5 CYCLE)', '"i" integer NOT NULL GENERATED ALWAYS AS IDENTITY(START WITH 1 INCREMENT BY 2 MINVALUE 1 MAXVALUE 100 CACHE 5 CYCLE)', IdentityColumn::class])]
    #[TestWith([Dialect::PostgreSql, 'b INT GENERATED BY DEFAULT AS IDENTITY', '"b" integer NOT NULL GENERATED BY DEFAULT AS IDENTITY', IdentityColumn::class])]
    #[TestWith([Dialect::PostgreSql, 'n INT NOT NULL DEFAULT 1', '"n" integer NOT NULL DEFAULT 1', SuppliedColumn::class])]
    #[TestWith([Dialect::Sqlite, 'id INTEGER PRIMARY KEY AUTOINCREMENT', '"id" "integer" NOT NULL PRIMARY KEY AUTOINCREMENT', AutoIncrementColumn::class])]
    public function testWriteSerializesNullabilityAndGenerationFromTheColumn(Dialect $dialect, string $column, string $expected, string $generation): void
    {
        $binder = new Binder((new SchemaBuilder($dialect))->build());
        $statement = $binder->bind('CREATE TABLE t (a INT, ' . $column . ')');
        self::assertInstanceOf(CreateTableStatement::class, $statement);
        $definition = $statement->definition->table->columns[1];
        self::assertInstanceOf($generation, $definition->generation);
        self::assertSame($expected, Columns::write($definition, $dialect)->toString());
        $rebound = $binder->bind($statement->toString());
        self::assertInstanceOf(CreateTableStatement::class, $rebound);
        self::assertInstanceOf($generation, $rebound->definition->table->columns[1]->generation);
        self::assertSame($definition->nullability, $rebound->definition->table->columns[1]->nullability);
        self::assertSame($expected, Columns::write($rebound->definition->table->columns[1], $dialect)->toString());
    }

    public function testWritePlacesAttributesBetweenTheTypeAndNullability(): void
    {
        $statement = (new Binder((new SchemaBuilder(Dialect::MySql))->build()))->bind("CREATE TABLE t (a VARCHAR(10) NOT NULL COMMENT 'c' DEFAULT 'x')");
        self::assertInstanceOf(CreateTableStatement::class, $statement);
        self::assertSame("`a` varchar(10) COMMENT 'c' NOT NULL DEFAULT 'x'", Columns::write($statement->definition->table->columns[0], Dialect::MySql)->toString());
    }

    #[TestWith([Dialect::MySql, 'mysql-8.4.7', 'CREATE TABLE t(a VARCHAR(36) DEFAULT (UUID()), b INT DEFAULT -1, c DATE DEFAULT (CURRENT_DATE), d DATETIME DEFAULT CURRENT_TIMESTAMP)', 'CREATE TABLE `t`(`a` varchar(36) DEFAULT (`UUID`()), `b` integer DEFAULT - 1, `c` date DEFAULT (CURRENT_DATE), `d` datetime DEFAULT CURRENT_TIMESTAMP)'])]
    #[TestWith([Dialect::MySql, 'mysql-5.7.44', "CREATE TABLE t(a INT DEFAULT -1, b VARCHAR(3) DEFAULT 'x')", "CREATE TABLE `t`(`a` integer DEFAULT - 1, `b` varchar(3) DEFAULT 'x')"])]
    #[TestWith([Dialect::Sqlite, null, 'CREATE TABLE t(a INT DEFAULT (random()), b TEXT DEFAULT CURRENT_DATE)', 'CREATE TABLE "main"."t"("a" "int" DEFAULT (random()), "b" "text" DEFAULT CURRENT_DATE)'])]
    #[TestWith([Dialect::PostgreSql, null, 'CREATE TABLE t(a UUID DEFAULT gen_random_uuid())', 'CREATE TABLE "public"."t"("a" uuid DEFAULT "gen_random_uuid"())'])]
    public function testDefaultValueParenthesizesExpressionDefaults(Dialect $dialect, ?string $version, string $sql, string $expected): void
    {
        $binder = new Binder((new SchemaBuilder($dialect, grammarVersion: $version))->build());
        $statement = $binder->bind($sql);
        self::assertSame($expected, $statement->toString());
        self::assertSame($expected, $binder->bind($expected)->toString());
    }
}
