<?php

declare(strict_types=1);

namespace Tests\Unit\Serialization\Definition;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Medium;
use PHPUnit\Framework\Attributes\TestWith;
use PHPUnit\Framework\TestCase;
use SqlSemantics\Binder;
use SqlSemantics\Dialect;
use SqlSemantics\Model\Statement\CreateTableStatement;
use SqlSemantics\Schema\Column\AutoIncrementColumn;
use SqlSemantics\Schema\Column\ComputedColumn;
use SqlSemantics\Schema\Column\IdentityColumn;
use SqlSemantics\Schema\Column\SuppliedColumn;
use SqlSemantics\SchemaBuilder;
use SqlSemantics\Serialization\Definition\Columns;

#[CoversClass(Columns::class)]
#[Medium]
final class ColumnsTest extends TestCase
{
    /**
     * @param class-string<AutoIncrementColumn|ComputedColumn|IdentityColumn|SuppliedColumn> $generation
     */
    #[TestWith([Dialect::MySql, 'e TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP', '`e` timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP', SuppliedColumn::class])]
    #[TestWith([Dialect::MySql, 'b INT GENERATED ALWAYS AS (a + 1) STORED', '`b` integer GENERATED ALWAYS AS((`a` + 1)) STORED', ComputedColumn::class])]
    #[TestWith([Dialect::MySql, 'c INT AS (a) VIRTUAL', '`c` integer GENERATED ALWAYS AS(`a`) VIRTUAL', ComputedColumn::class])]
    #[TestWith([Dialect::MySql, 'd INT NOT NULL AUTO_INCREMENT', '`d` integer NOT NULL AUTO_INCREMENT', AutoIncrementColumn::class])]
    #[TestWith([Dialect::PostgreSql, 'i INT GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 2 MINVALUE 1 MAXVALUE 100 CACHE 5 CYCLE)', '"i" integer NOT NULL GENERATED ALWAYS AS IDENTITY(START WITH 1 INCREMENT BY 2 MINVALUE 1 MAXVALUE 100 CACHE 5 CYCLE)', IdentityColumn::class])]
    #[TestWith([Dialect::PostgreSql, 'b INT GENERATED BY DEFAULT AS IDENTITY', '"b" integer NOT NULL GENERATED BY DEFAULT AS IDENTITY', IdentityColumn::class])]
    #[TestWith([Dialect::PostgreSql, 'n INT NOT NULL DEFAULT 1', '"n" integer NOT NULL DEFAULT 1', SuppliedColumn::class])]
    #[TestWith([Dialect::Sqlite, 'id INTEGER PRIMARY KEY AUTOINCREMENT', '"id" "integer" NOT NULL PRIMARY KEY AUTOINCREMENT', AutoIncrementColumn::class])]
    public function testWriteSerializesNullabilityAndGenerationFromTheColumn(Dialect $dialect, string $column, string $expected, string $generation): void
    {
        $binder = new Binder((new SchemaBuilder($dialect))->build());
        $statement = $binder->bind('CREATE TABLE t (a INT, ' . $column . ')');
        self::assertInstanceOf(CreateTableStatement::class, $statement);
        $definition = $statement->definition->table->columns[1];
        self::assertInstanceOf($generation, $definition->generation);
        self::assertSame($expected, Columns::write($definition, $dialect)->toString());
        $rebound = $binder->bind((new \SqlSemantics\SimpleSerializer())->serialize($statement));
        self::assertInstanceOf(CreateTableStatement::class, $rebound);
        self::assertInstanceOf($generation, $rebound->definition->table->columns[1]->generation);
        self::assertSame($definition->nullability, $rebound->definition->table->columns[1]->nullability);
        self::assertSame($expected, Columns::write($rebound->definition->table->columns[1], $dialect)->toString());
    }

    public function testWritePlacesAttributesBetweenTheTypeAndNullability(): void
    {
        $statement = (new Binder((new SchemaBuilder(Dialect::MySql))->build()))->bind("CREATE TABLE t (a VARCHAR(10) NOT NULL COMMENT 'c' DEFAULT 'x')");
        self::assertInstanceOf(CreateTableStatement::class, $statement);
        self::assertSame("`a` varchar(10) COMMENT 'c' NOT NULL DEFAULT 'x'", Columns::write($statement->definition->table->columns[0], Dialect::MySql)->toString());
    }

    #[TestWith([Dialect::MySql, 'mysql-8.4.7', 'CREATE TABLE t(a VARCHAR(36) DEFAULT (UUID()), b INT DEFAULT -1, c DATE DEFAULT (CURRENT_DATE), d DATETIME DEFAULT CURRENT_TIMESTAMP)', 'CREATE TABLE `t`(`a` varchar(36) DEFAULT (`UUID`()), `b` integer DEFAULT - 1, `c` date DEFAULT (CURRENT_DATE), `d` datetime DEFAULT CURRENT_TIMESTAMP)'])]
    #[TestWith([Dialect::MySql, 'mysql-5.7.44', "CREATE TABLE t(a INT DEFAULT -1, b VARCHAR(3) DEFAULT 'x')", "CREATE TABLE `t`(`a` integer DEFAULT - 1, `b` varchar(3) DEFAULT 'x')"])]
    #[TestWith([Dialect::Sqlite, null, 'CREATE TABLE t(a INT DEFAULT (random()), b TEXT DEFAULT CURRENT_DATE)', 'CREATE TABLE "main"."t"("a" "int" DEFAULT (random()), "b" "text" DEFAULT CURRENT_DATE)'])]
    #[TestWith([Dialect::PostgreSql, null, 'CREATE TABLE t(a UUID DEFAULT gen_random_uuid())', 'CREATE TABLE "public"."t"("a" uuid DEFAULT "gen_random_uuid"())'])]
    public function testDefaultValueParenthesizesExpressionDefaults(Dialect $dialect, ?string $version, string $sql, string $expected): void
    {
        $binder = new Binder((new SchemaBuilder($dialect, grammarVersion: $version))->build());
        $statement = $binder->bind($sql);
        self::assertSame($expected, (new \SqlSemantics\SimpleSerializer())->serialize($statement));
        self::assertSame($expected, (new \SqlSemantics\SimpleSerializer())->serialize($binder->bind($expected)));
    }

    public function testDefaultValueWritesTheExpression(): void
    {
        self::assertSame('1', Columns::defaultValue(\SqlSemantics\Model\Expression::literal(1, Dialect::PostgreSql), Dialect::PostgreSql)->toString());
    }


    public function testWriteKeepsAMySqlGeneratedExpressionBeforeTheAttributes(): void
    {
        $binder = new Binder((new SchemaBuilder(Dialect::MySql))->build());
        $statement = $binder->bind('CREATE TABLE t (a INT, d INT GENERATED ALWAYS AS (a) STORED NOT NULL)');
        self::assertSame('CREATE TABLE `t`(`a` integer, `d` integer GENERATED ALWAYS AS(`a`) STORED NOT NULL)', (new \SqlSemantics\SimpleSerializer())->serialize($statement));
        self::assertSame((new \SqlSemantics\SimpleSerializer())->serialize($statement), (new \SqlSemantics\SimpleSerializer())->serialize($binder->bind((new \SqlSemantics\SimpleSerializer())->serialize($statement))));
    }

    #[TestWith([Dialect::MySql, 'mysql-5.6.51', 'ALTER TABLE t MODIFY a INT NULL PRIMARY KEY', 'ALTER TABLE `t` MODIFY COLUMN `a` integer NULL PRIMARY KEY'])]
    #[TestWith([Dialect::MySql, 'mysql-8.4.7', 'ALTER TABLE t ADD c INT NULL DEFAULT 1', 'ALTER TABLE `t` ADD COLUMN `c` integer NULL DEFAULT 1'])]
    #[TestWith([Dialect::MySql, 'mysql-8.4.7', 'CREATE TABLE u (c INT NULL, d INT)', 'CREATE TABLE `u`(`c` integer NULL, `d` integer)'])]
    #[TestWith([Dialect::PostgreSql, null, 'CREATE TABLE u (c int NULL)', 'CREATE TABLE "public"."u"("c" integer NULL)'])]
    #[TestWith([Dialect::MySql, 'mysql-8.4.7', 'CREATE TABLE u (c INT AUTO_INCREMENT NULL, KEY (c))', 'CREATE TABLE `u`(`c` integer AUTO_INCREMENT NULL, INDEX(`c`))'])]
    #[TestWith([Dialect::MySql, 'mysql-5.7.44', 'ALTER TABLE t MODIFY a INT NOT NULL NULL', 'ALTER TABLE `t` MODIFY COLUMN `a` integer NULL'])]
    public function testWriteKeepsADeclaredNull(Dialect $dialect, ?string $version, string $sql, string $expected): void
    {
        $binder = new Binder((new SchemaBuilder($dialect, grammarVersion: $version))->build('CREATE TABLE t (a INT)'));
        $written = (new \SqlSemantics\SimpleSerializer())->serialize($binder->bind($sql));
        self::assertSame($expected, $written);
        self::assertSame($expected, (new \SqlSemantics\SimpleSerializer())->serialize($binder->bind($written)));
    }

    #[TestWith(['mysql-5.6.51', 'CREATE TABLE u (a INT SERIAL DEFAULT VALUE, b INT)', 'CREATE TABLE `u`(`a` integer SERIAL DEFAULT VALUE, `b` integer)'])]
    #[TestWith(['mysql-5.7.44', 'CREATE TABLE u (a BIGINT UNSIGNED SERIAL DEFAULT VALUE NULL)', 'CREATE TABLE `u`(`a` bigint UNSIGNED SERIAL DEFAULT VALUE NULL)'])]
    #[TestWith(['mysql-8.0.44', 'CREATE TABLE u (a INT NULL SERIAL DEFAULT VALUE, UNIQUE (a))', 'CREATE TABLE `u`(`a` integer SERIAL DEFAULT VALUE, UNIQUE(`a`))'])]
    #[TestWith(['mysql-8.4.7', 'ALTER TABLE t ADD COLUMN b INT SERIAL DEFAULT VALUE', 'ALTER TABLE `t` ADD COLUMN `b` integer SERIAL DEFAULT VALUE'])]
    #[TestWith(['mysql-8.4.7', 'ALTER TABLE t ADD COLUMN (b INT SERIAL DEFAULT VALUE, c INT)', 'ALTER TABLE `t` ADD COLUMN(`b` integer SERIAL DEFAULT VALUE, `c` integer)'])]
    #[TestWith(['mysql-9.1.0', 'ALTER TABLE t MODIFY a INT SERIAL DEFAULT VALUE', 'ALTER TABLE `t` MODIFY COLUMN `a` integer SERIAL DEFAULT VALUE'])]
    public function testWriteKeepsTheMySqlSerialDefaultValueAttribute(string $version, string $sql, string $expected): void
    {
        $binder = new Binder((new SchemaBuilder(Dialect::MySql, grammarVersion: $version))->build('CREATE TABLE t (a INT)'));
        $written = (new \SqlSemantics\SimpleSerializer())->serialize($binder->bind($sql));
        self::assertSame($expected, $written);
        self::assertSame($expected, (new \SqlSemantics\SimpleSerializer())->serialize($binder->bind($written)));
    }

    public function testWriteFallsBackToAutoIncrementWhenTheSerialKeyIsGone(): void
    {
        $column = (new SchemaBuilder(Dialect::MySql))->build('CREATE TABLE t (a INT SERIAL DEFAULT VALUE)')->tables[0]->columns[0];
        self::assertSame('`a` integer SERIAL DEFAULT VALUE', Columns::write($column, Dialect::MySql)->toString());
        self::assertSame('`a` integer NOT NULL AUTO_INCREMENT', Columns::write($column, Dialect::MySql, serialKey: false)->toString());
    }

    public function testSerialKeyFindsTheUniqueKeyTheAttributeDeclares(): void
    {
        $table = (new SchemaBuilder(Dialect::MySql))->build('CREATE TABLE t (a INT SERIAL DEFAULT VALUE, b INT AUTO_INCREMENT UNIQUE, CONSTRAINT named UNIQUE (a))')->tables[0];
        self::assertSame(['a'], Columns::serialKey($table->columns[0], $table->constraints)?->localColumns());
        self::assertNull(Columns::serialKey($table->columns[0], array_slice($table->constraints, 2)));
        self::assertNull(Columns::serialKey($table->columns[1], $table->constraints));
    }

    public function testUnserialLeavesOutOnlyTheKeysSerialDefaultValueDeclares(): void
    {
        $table = (new SchemaBuilder(Dialect::MySql))->build('CREATE TABLE t (a INT SERIAL DEFAULT VALUE, b INT UNIQUE, UNIQUE (a))')->tables[0];
        self::assertCount(3, $table->constraints);
        self::assertSame([$table->constraints[1], $table->constraints[2]], Columns::unserial($table->columns, $table->constraints));
    }

    #[TestWith(['a serial', '"a" serial', 'integer'])]
    #[TestWith(['a serial4', '"a" serial', 'integer'])]
    #[TestWith(['a smallserial', '"a" smallserial', 'smallint'])]
    #[TestWith(['a serial2', '"a" smallserial', 'smallint'])]
    #[TestWith(['a bigserial', '"a" bigserial', 'bigint'])]
    #[TestWith(['a serial8 PRIMARY KEY', '"a" bigserial', 'bigint'])]
    #[TestWith(['a int4', '"a" integer', 'integer'])]
    public function testTypeWritesThePostgreSqlSerialTypeOfTheIntegerWidth(string $declaration, string $expected, string $type): void
    {
        $column = (new SchemaBuilder(Dialect::PostgreSql, grammarVersion: 'pg-17.2'))->build('CREATE TABLE t (' . $declaration . ')')->tables[0]->columns[0];
        self::assertSame($type, $column->type->name);
        self::assertSame($expected, Columns::write($column, Dialect::PostgreSql)->toString());
        self::assertSame(substr($expected, 4), Columns::type($column)->toString());
    }

    public function testGenerationWritesTheValueSourceInTheDialectSpelling(): void
    {
        self::assertSame('AUTO_INCREMENT', (new \SqlSemantics\Model\Sql\Tree('column', Columns::generation(new AutoIncrementColumn(), Dialect::MySql, \SqlSemantics\Model\Write\Policy\ConstraintResponse::Default, false, true)))->toString());
        self::assertSame('SERIAL DEFAULT VALUE', (new \SqlSemantics\Model\Sql\Tree('column', Columns::generation(new AutoIncrementColumn(true), Dialect::MySql, \SqlSemantics\Model\Write\Policy\ConstraintResponse::Default, true, true)))->toString());
        self::assertSame('PRIMARY KEY AUTOINCREMENT', (new \SqlSemantics\Model\Sql\Tree('column', Columns::generation(new AutoIncrementColumn(), Dialect::Sqlite, \SqlSemantics\Model\Write\Policy\ConstraintResponse::Default, false, true)))->toString());
        self::assertSame('', (new \SqlSemantics\Model\Sql\Tree('column', Columns::generation(new SuppliedColumn(), Dialect::PostgreSql, \SqlSemantics\Model\Write\Policy\ConstraintResponse::Default, false, true)))->toString());
        self::assertSame('', (new \SqlSemantics\Model\Sql\Tree('column', Columns::generation(new \SqlSemantics\Schema\Column\SerialColumn(), Dialect::PostgreSql, \SqlSemantics\Model\Write\Policy\ConstraintResponse::Default, false, true)))->toString());
    }
}
