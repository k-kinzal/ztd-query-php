<?php

declare(strict_types=1);

namespace Tests\Unit\Schema\Column;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Medium;
use PHPUnit\Framework\TestCase;
use SqlSemantics\Dialect;
use SqlSemantics\Schema\Column\IdentityColumn;
use SqlSemantics\Schema\Column\IdentityMode;
use SqlSemantics\SchemaBuilder;

#[CoversClass(IdentityMode::class)]
#[Medium]
final class IdentityModeTest extends TestCase
{
    public function testRepresentsBothOverridePolicies(): void
    {
        self::assertSame(['always', 'by-default'], array_column(IdentityMode::cases(), 'value'));
    }

    public function testClassifiesGeneratedAlwaysAndByDefault(): void
    {
        $table = (new SchemaBuilder(Dialect::PostgreSql))->build('CREATE TABLE t(a INTEGER GENERATED ALWAYS AS IDENTITY, b INTEGER GENERATED BY DEFAULT AS IDENTITY)')->tables[0];
        self::assertInstanceOf(IdentityColumn::class, $table->columns[0]->generation);
        self::assertInstanceOf(IdentityColumn::class, $table->columns[1]->generation);
        self::assertSame(IdentityMode::Always, $table->columns[0]->generation->mode);
        self::assertSame(IdentityMode::ByDefault, $table->columns[1]->generation->mode);
    }
}
