<?php

declare(strict_types=1);

namespace Tests\Unit\Schema\Column;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Medium;
use PHPUnit\Framework\TestCase;
use SqlSemantics\Dialect;
use SqlSemantics\Model\Expression;
use SqlSemantics\Model\Scalar\Value\Literal;
use SqlSemantics\Schema\Column\IdentityColumn;
use SqlSemantics\Schema\Column\IdentityMode;
use SqlSemantics\Schema\Column\SequenceOptions;
use SqlSemantics\SchemaBuilder;
use SqlSemantics\Serialization\Definition\Columns;

#[CoversClass(IdentityColumn::class)]
#[Medium]
final class IdentityColumnTest extends TestCase
{
    public function testExpressionsAreEmptyBecauseTheSequenceSuppliesTheValue(): void
    {
        $column = new IdentityColumn(IdentityMode::Always);
        self::assertSame([], $column->expressions());
        self::assertNull($column->sequence->start);
        self::assertNull($column->sequence->cycle);
    }

    public function testBindsTheIdentityModeAndSequenceAttributes(): void
    {
        $column = (new SchemaBuilder(Dialect::PostgreSql))->build('CREATE TABLE t(id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 5 INCREMENT BY 2))')->tables[0]->columns[0];
        self::assertInstanceOf(IdentityColumn::class, $column->generation);
        self::assertSame(IdentityMode::ByDefault, $column->generation->mode);
        self::assertSame('5', $column->generation->sequence->start?->text);
        self::assertSame('2', $column->generation->sequence->increment?->text);
    }

    public function testSerializesADeclaredSequence(): void
    {
        $column = (new SchemaBuilder(Dialect::PostgreSql))->build('CREATE TABLE t(a INTEGER)')->tables[0]->columns[0];
        $start = Expression::literal(5, Dialect::PostgreSql);
        self::assertInstanceOf(Literal::class, $start);
        $generation = new IdentityColumn(IdentityMode::Always, new SequenceOptions($start, cycle: false));
        self::assertSame('"a" integer GENERATED ALWAYS AS IDENTITY(START WITH 5 NO CYCLE)', Columns::write($column->withGeneration($generation), Dialect::PostgreSql)->toString());
    }
}
