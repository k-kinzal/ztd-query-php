<?php

declare(strict_types=1);

namespace Tests\Unit\Model\Definition\Relation\Identity;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Medium;
use PHPUnit\Framework\TestCase;
use SqlSemantics\Binder;
use SqlSemantics\Dialect;
use SqlSemantics\Model\Definition\Relation;
use SqlSemantics\Model\Statement\Definition\PostgreSql\Relation\AlterRelationStatement;
use SqlSemantics\Model\Validation\InvalidStructure;
use SqlSemantics\SchemaBuilder;

#[CoversClass(Relation\Identity\SequenceStorage::class)]
#[Medium]
final class SequenceStorageTest extends TestCase
{
    public function testBindsAndWritesTheAction(): void
    {
        $statement = (new Binder((new SchemaBuilder(Dialect::PostgreSql))->build('CREATE TABLE t(id INTEGER)')))->bind('ALTER TABLE t ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (AS smallint)', strict: false);
        self::assertInstanceOf(AlterRelationStatement::class, $statement);
        self::assertInstanceOf(Relation\Identity\AddColumnIdentity::class, $statement->actions[0]);
        self::assertInstanceOf(Relation\Identity\SequenceStorage::class, $statement->actions[0]->options[0]);
        self::assertSame('smallint', $statement->actions[0]->options[0]->type->name);
        self::assertSame('ALTER TABLE "t" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY(AS smallint)', $statement->toString());
    }

    public function testRejectsATypeFromAnotherDatabaseLanguage(): void
    {
        $this->expectException(InvalidStructure::class);
        new Relation\Identity\SequenceStorage(\SqlSemantics\Type\TypeDescriptor::builtin(Dialect::MySql, 'smallint'));
    }
}
