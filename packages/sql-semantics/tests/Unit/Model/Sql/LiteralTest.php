final class LiteralTest extends TestCase
{
    #[\PHPUnit\Framework\Attributes\TestWith([null,Dialect::PostgreSql,'NULL','unknown'])]
    #[\PHPUnit\Framework\Attributes\TestWith([true,Dialect::PostgreSql,'TRUE','boolean'])]
    #[\PHPUnit\Framework\Attributes\TestWith([false,Dialect::Sqlite,'FALSE','integer'])]
    #[\PHPUnit\Framework\Attributes\TestWith([2147483648,Dialect::PostgreSql,'2147483648','bigint'])]
    #[\PHPUnit\Framework\Attributes\TestWith([3,Dialect::MySql,'3','integer'])]
    #[\PHPUnit\Framework\Attributes\TestWith([1.25,Dialect::Sqlite,'1.25','real'])]
    #[\PHPUnit\Framework\Attributes\TestWith([1.25,Dialect::PostgreSql,'1.25','numeric'])]
    #[\PHPUnit\Framework\Attributes\TestWith(["a'b",Dialect::PostgreSql,"'a''b'",'unknown'])]
    #[\PHPUnit\Framework\Attributes\TestWith(['a\\b',Dialect::MySql,"'a\\\\b'",'text'])]
    public function testEncodePreservesTheScalarValue(string|int|float|bool|null $value, Dialect $dialect, string $sql, string $type): void
    {
        self::assertSame([$sql,$type], Sql\Literal::encode($value, $dialect));
    }
    public function testEncodeRejectsNonFiniteNumbers(): void
    {
        $this->expectException(InvalidStructure::class);
        Sql\Literal::encode(INF, Dialect::PostgreSql);
    }

    #[\PHPUnit\Framework\Attributes\TestWith([2147483647,'integer'])]
    #[\PHPUnit\Framework\Attributes\TestWith([-2147483648,'integer'])]
    #[\PHPUnit\Framework\Attributes\TestWith([-2147483649,'bigint'])]
    public function testEncodeKeepsPostgreSqlIntegerBoundaries(int $value, string $type): void
    {
        self::assertSame([(string) $value,$type], Sql\Literal::encode($value, Dialect::PostgreSql));
        self::assertSame([(string) $value,'integer'], Sql\Literal::encode($value, Dialect::MySql));
    }
    public function testEncodeDistinguishesDecimalAndExponentForms(): void
    {
        self::assertSame(['1.0e+30','double precision'], Sql\Literal::encode(1e30, Dialect::MySql));
        self::assertSame(['1.0e+30','numeric'], Sql\Literal::encode(1e30, Dialect::PostgreSql));
        self::assertSame(['1.5','numeric'], Sql\Literal::encode(1.5, Dialect::MySql));
    }
}
