<?php

declare(strict_types=1);

namespace Tests\Unit\Ast\Definition;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Medium;
use PHPUnit\Framework\Attributes\TestWith;
use PHPUnit\Framework\TestCase;
use SqlSemantics\Ast\Definition\ValueSources;
use SqlSemantics\Dialect;
use SqlSemantics\InvalidSql;
use SqlSemantics\Model\Validation\InputViolation;
use SqlSemantics\Schema\Column\SuppliedColumn;
use SqlSemantics\SchemaBuilder;

#[CoversClass(ValueSources::class)]
#[Medium]
final class ValueSourcesTest extends TestCase
{
    #[TestWith(['mysql', 'mysql-8.4.7', 'a int DEFAULT 1 DEFAULT 5', '5'])]
    #[TestWith(['mysql', 'mysql-5.6.51', 'a int DEFAULT 1 DEFAULT 5', '5'])]
    #[TestWith(['mysql', 'mysql-8.4.7', 'a int DEFAULT (1) DEFAULT (5)', '5'])]
    #[TestWith(['mysql', 'mysql-8.4.7', 'a int DEFAULT NULL DEFAULT (5)', '5'])]
    #[TestWith(['mysql', 'mysql-8.4.7', 'a int DEFAULT (5) DEFAULT NULL', '5'])]
    #[TestWith(['mysql', 'mysql-8.4.7', 'a int DEFAULT 5 DEFAULT NULL', 'NULL'])]
    #[TestWith(['sqlite', 'sqlite-3.47.2', 'a int DEFAULT 1 DEFAULT 5', '5'])]
    public function testDefaultTakesTheDefaultTheServerKeeps(string $dialect, string $version, string $column, string $expected): void
    {
        $generation = (new SchemaBuilder(Dialect::from($dialect), grammarVersion: $version))->build('CREATE TABLE t (' . $column . ')')->tables[0]->columns[0]->generation;
        self::assertInstanceOf(SuppliedColumn::class, $generation);
        self::assertSame($expected, trim($generation->default?->source->toString() ?? ''));
    }

    #[TestWith(['a int DEFAULT 1 DEFAULT 5'])]
    #[TestWith(['a int DEFAULT 1 CONSTRAINT x DEFAULT 2'])]
    #[TestWith(['a int DEFAULT 1 GENERATED ALWAYS AS IDENTITY'])]
    #[TestWith(['a int GENERATED ALWAYS AS IDENTITY DEFAULT 1'])]
    #[TestWith(['a int DEFAULT 1 GENERATED ALWAYS AS (2) STORED'])]
    #[TestWith(['a int GENERATED ALWAYS AS IDENTITY GENERATED BY DEFAULT AS IDENTITY'])]
    #[TestWith(['a int GENERATED ALWAYS AS (1) STORED GENERATED ALWAYS AS (2) STORED'])]
    #[TestWith(['a int GENERATED ALWAYS AS (1) STORED GENERATED ALWAYS AS IDENTITY'])]
    public function testDefaultRejectsASecondPostgreSqlValueSource(string $column): void
    {
        $this->expectException(InvalidSql::class);
        $this->expectExceptionMessage(InputViolation::ValueSources->message());
        (new SchemaBuilder(Dialect::PostgreSql, grammarVersion: 'pg-17.2'))->build('CREATE TABLE t (' . $column . ')');
    }

    #[TestWith(['a int DEFAULT 1 GENERATED ALWAYS AS (2)'])]
    #[TestWith(['a int GENERATED ALWAYS AS (2) DEFAULT 1'])]
    #[TestWith(['a int AS (1) AS (2)'])]
    public function testDefaultRejectsASqliteDefaultOrSecondGenerationBesideAGeneration(string $column): void
    {
        $this->expectException(InvalidSql::class);
        $this->expectExceptionMessage(InputViolation::ValueSources->message());
        (new SchemaBuilder(Dialect::Sqlite, grammarVersion: 'sqlite-3.47.2'))->build('CREATE TABLE t (' . $column . ')');
    }

    public function testDefaultAcceptsASingleSourceOfEachDialect(): void
    {
        $postgres = (new SchemaBuilder(Dialect::PostgreSql))->build('CREATE TABLE t (a int DEFAULT 1 NOT NULL, b int GENERATED ALWAYS AS IDENTITY, c int GENERATED ALWAYS AS (a) STORED)')->tables[0];
        $sqlite = (new SchemaBuilder(Dialect::Sqlite))->build('CREATE TABLE t (a INTEGER PRIMARY KEY AUTOINCREMENT DEFAULT 3, b int AS (a))')->tables[0];
        self::assertCount(3, $postgres->columns);
        self::assertCount(2, $sqlite->columns);
    }

    #[TestWith(['mysql-8.4.7', 'a int DEFAULT 1 DEFAULT (5)'])]
    #[TestWith(['mysql-8.4.7', 'a int DEFAULT (1) DEFAULT 5'])]
    #[TestWith(['mysql-8.4.7', 'a timestamp NULL DEFAULT CURRENT_TIMESTAMP DEFAULT (NOW())'])]
    #[TestWith(['mysql-8.4.7', 'a int DEFAULT (NULL) AUTO_INCREMENT UNIQUE'])]
    #[TestWith(['mysql-8.4.7', 'a int AS (1) DEFAULT NULL'])]
    #[TestWith(['mysql-8.4.7', 'a int AS (1) DEFAULT 1'])]
    #[TestWith(['mysql-8.4.7', 'a SERIAL DEFAULT 1'])]
    #[TestWith(['mysql-5.6.51', 'a int DEFAULT 1 AUTO_INCREMENT KEY'])]
    #[TestWith(['mysql-5.7.44', 'a int AUTO_INCREMENT DEFAULT 1 KEY'])]
    #[TestWith(['mysql-8.4.7', 'a int DEFAULT 1 SERIAL DEFAULT VALUE'])]
    #[TestWith(['mysql-8.4.7', 'a int DEFAULT NULL DEFAULT 5 AUTO_INCREMENT UNIQUE'])]
    public function testMySqlRejectsTheDefaultsTheServerRejects(string $version, string $column): void
    {
        $this->expectException(InvalidSql::class);
        $this->expectExceptionMessage(InputViolation::ValueSources->message());
        (new SchemaBuilder(Dialect::MySql, grammarVersion: $version))->build('CREATE TABLE t (' . $column . ')');
    }

    #[TestWith(['a int DEFAULT NULL AUTO_INCREMENT UNIQUE'])]
    #[TestWith(['a int DEFAULT 5 DEFAULT NULL AUTO_INCREMENT UNIQUE'])]
    #[TestWith(['a int DEFAULT NULL SERIAL DEFAULT VALUE'])]
    #[TestWith(['a SERIAL DEFAULT NULL'])]
    public function testMySqlAcceptsDefaultNullOnACounterColumn(string $column): void
    {
        $table = (new SchemaBuilder(Dialect::MySql, grammarVersion: 'mysql-8.4.7'))->build('CREATE TABLE t (' . $column . ')')->tables[0];
        self::assertInstanceOf(\SqlSemantics\Schema\Column\AutoIncrementColumn::class, $table->columns[0]->generation);
    }
}
