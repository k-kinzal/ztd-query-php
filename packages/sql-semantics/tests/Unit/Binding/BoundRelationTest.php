#[CoversClass(\SqlSemantics\Type\TypeDescriptor::class)]
#[Medium]
final class BoundRelationTest extends TestCase
{
    public function testKeepsScopeAndRelationAtTheSameStage(): void
    {
        $case = new AnalysisCase();
        $tables = new \SqlSemantics\Binding\TableResolver($case->schema(), new \SqlSemantics\Ast\Identifiers(Dialect::PostgreSql), 'public');
        $from = $case->parser->parse('SELECT id FROM users')->find('from_clause')[0];
        $bound = (new \SqlSemantics\Analysis\FromReader($tables, new \SqlSemantics\Binding\IdentitySequence()))->read($from);
        self::assertNotNull($bound);
        self::assertSame($bound->relation, $bound->scope->relations[0]);
    }

}
