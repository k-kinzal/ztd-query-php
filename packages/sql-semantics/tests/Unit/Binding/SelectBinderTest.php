#[Medium]
final class SelectBinderTest extends TestCase
{
    #[TestWith([Dialect::PostgreSql])]
    #[TestWith([Dialect::MySql])]
    #[TestWith([Dialect::Sqlite])]
    public function testBindConstantQueriesWithoutARelation(Dialect $dialect): void
    {
        $schema = (new SchemaBuilder($dialect))->build();
        $statement = (new Binder($schema))->bind('SELECT DISTINCT 1 AS one');
        self::assertNull($statement->from);
        self::assertSame([], $statement->relations);
        self::assertTrue($statement->distinct);
        self::assertNull($statement->where);
        self::assertNull($statement->limit);
        self::assertNull($statement->offset);
    }
}
