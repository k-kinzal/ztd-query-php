    /**
     * @param class-string<object> $class
     */
    #[TestWith(['ALTER TABLE t ALTER id ADD GENERATED ALWAYS AS IDENTITY (AS bigint START 5 CACHE 10 SEQUENCE NAME s OWNED BY NONE NO MINVALUE NO CYCLE LOGGED)', \SqlSemantics\Model\Statement\Definition\PostgreSql\Relation\AlterRelationStatement::class, 'ALTER TABLE "t" ALTER COLUMN "id" ADD GENERATED ALWAYS AS IDENTITY(AS bigint START WITH 5 CACHE 10 SEQUENCE NAME "s" OWNED BY NONE NO MINVALUE NO CYCLE LOGGED)'])]
