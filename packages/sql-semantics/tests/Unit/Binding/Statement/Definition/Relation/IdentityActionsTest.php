    /**
     * @param class-string<object> $class
     */
    #[TestWith(['ALTER TABLE t ALTER id SET MINVALUE -100 SET MAXVALUE +100', \SqlSemantics\Model\Statement\Definition\PostgreSql\Relation\AlterRelationStatement::class, 'ALTER TABLE "t" ALTER COLUMN "id" SET MINVALUE -100 SET MAXVALUE +100'])]
