    #[TestWith(['ALTER TABLE t ALTER id add generated always as identity', 'ALTER TABLE "t" ALTER COLUMN "id" ADD GENERATED ALWAYS AS IDENTITY'])]
    #[TestWith(['ALTER TABLE t ALTER id ADD GENERATED ALWAYS AS IDENTITY (OWNED BY none.t.id)', 'ALTER TABLE "t" ALTER COLUMN "id" ADD GENERATED ALWAYS AS IDENTITY(OWNED BY "none"."t"."id")'])]
    #[TestWith(['ALTER TABLE t ALTER id ADD GENERATED ALWAYS AS IDENTITY (OWNED BY db.app.t.id)', 'ALTER TABLE "t" ALTER COLUMN "id" ADD GENERATED ALWAYS AS IDENTITY(OWNED BY "db"."app"."t"."id")'])]
    #[TestWith(['ALTER TABLE t ALTER id ADD GENERATED ALWAYS AS IDENTITY (SEQUENCE NAME db.app.s)', 'ALTER TABLE "t" ALTER COLUMN "id" ADD GENERATED ALWAYS AS IDENTITY(SEQUENCE NAME "db"."app"."s")'])]
    #[TestWith(['ALTER TABLE t ALTER id ADD GENERATED ALWAYS AS IDENTITY (RESTART 5)', 'ALTER TABLE "t" ALTER COLUMN "id" ADD GENERATED ALWAYS AS IDENTITY(RESTART WITH 5)'])]
    public function testAddKeepsEveryWrittenOption(string $sql, string $expected): void
    {
        $statement = (new Binder((new SchemaBuilder(Dialect::PostgreSql))->build('CREATE TABLE t(id INTEGER, n INTEGER)')))->bind($sql, strict: false);
        self::assertSame($expected, (new \SqlSemantics\SimpleSerializer())->serialize($statement));
    }

    #[TestWith(['ALTER TABLE t ALTER id ADD GENERATED ALWAYS AS IDENTITY (OWNED BY a.b.c.d.e)'])]
    #[TestWith(['ALTER TABLE t ALTER id ADD GENERATED ALWAYS AS IDENTITY (SEQUENCE NAME a.db.app.s)'])]
    public function testOptionRejectsAnOverlongName(string $sql): void
    {
        $binder = new Binder((new SchemaBuilder(Dialect::PostgreSql))->build('CREATE TABLE t(id INTEGER, n INTEGER)'));
        $this->expectException(InvalidSql::class);
        $this->expectExceptionMessage('The object name does not have the number of components its object class requires.');
        $binder->bind($sql, strict: false);
    }

    public function testModeReadsTheParsedKeyword(): void
    {
        $parser = new DialectParser(Dialect::PostgreSql);
        self::assertSame(IdentityMode::Always, IdentityActions::mode(Tree::outer($parser->parse('ALTER TABLE t ALTER id SET GENERATED always'), ['generated_when'])[0]));
        self::assertSame(IdentityMode::ByDefault, IdentityActions::mode(Tree::outer($parser->parse('ALTER TABLE t ALTER id SET GENERATED BY DEFAULT'), ['generated_when'])[0]));
    }

    public function testOptionReadsAParsedSequenceOption(): void
    {
        $context = new QueryContext(new TableResolver((new SchemaBuilder(Dialect::PostgreSql))->build(), new Identifiers(Dialect::PostgreSql), 'public'));
        $option = IdentityActions::option(Tree::outer((new DialectParser(Dialect::PostgreSql))->parse('ALTER TABLE t ALTER id SET CACHE 20'), ['SeqOptElem'])[0], new Scope(new Identifiers(Dialect::PostgreSql)), $context);
        self::assertInstanceOf(SequenceValueChange::class, $option);
        self::assertSame(SequenceAttribute::Cache, $option->attribute);
        self::assertSame('20', $option->value->text);
    }

    public function testOwnerReadsNoneAsNoColumn(): void
    {
        $context = new QueryContext(new TableResolver((new SchemaBuilder(Dialect::PostgreSql))->build(), new Identifiers(Dialect::PostgreSql), 'public'));
        $parser = new DialectParser(Dialect::PostgreSql);
        self::assertNull(IdentityActions::owner(Tree::outer(Tree::outer($parser->parse('ALTER SEQUENCE s OWNED BY NONE'), ['SeqOptElem'])[0], ['any_name'])[0], $context));
        self::assertSame(['t', 'id'], IdentityActions::owner(Tree::outer(Tree::outer($parser->parse('ALTER SEQUENCE s OWNED BY t.id'), ['SeqOptElem'])[0], ['any_name'])[0], $context)?->parts);
    }

    public function testIntegerReadsTheParsedNumber(): void
    {
        $number = Tree::outer((new DialectParser(Dialect::PostgreSql))->parse('ALTER SEQUENCE s CACHE 20'), ['NumericOnly'])[0];
        self::assertSame('20', IdentityActions::integer($number, new Scope(new Identifiers(Dialect::PostgreSql)))->text);
    }

    public function testValueReadsNothingWithoutANumber(): void
    {
        self::assertNull(IdentityActions::value(null, new Scope(new Identifiers(Dialect::PostgreSql))));
    }

    public function testValueRejectsANonLiteralExpression(): void
    {
        $expression = Tree::outer((new DialectParser(Dialect::PostgreSql))->parse('SELECT 1 + 2'), ['a_expr'])[0];
        $this->expectException(InvalidSql::class);
        $this->expectExceptionMessage(InputViolation::SequenceAttribute->message());
        IdentityActions::value($expression, new Scope(new Identifiers(Dialect::PostgreSql)));
    }

    public function testSignedLeavesANonLiteralTokenUnbound(): void
    {
        self::assertNull(IdentityActions::signed('-', (new DialectParser(Dialect::PostgreSql))->parse('SELECT abc')->tokens()[1]));
    }

    public function testSignedRejectsASignedString(): void
    {
        $this->expectException(InvalidSql::class);
        $this->expectExceptionMessage(InputViolation::SequenceAttribute->message());
        IdentityActions::signed('-', (new DialectParser(Dialect::PostgreSql))->parse("SELECT 'x'")->tokens()[1]);
    }
}
