    /**
     * @param class-string<object> $class
     */
    #[TestWith(['ALTER TABLE t ALTER id RESTART WITH -5', \SqlSemantics\Model\Statement\Definition\PostgreSql\Relation\AlterRelationStatement::class, 'ALTER TABLE "t" ALTER COLUMN "id" RESTART WITH -5'])]
