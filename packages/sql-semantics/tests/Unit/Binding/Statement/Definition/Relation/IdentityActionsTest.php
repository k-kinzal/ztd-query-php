    /**
     * @param class-string<object> $class
     */
    #[TestWith(['ALTER TABLE t ALTER id SET CACHE 20', \SqlSemantics\Model\Statement\Definition\PostgreSql\Relation\AlterRelationStatement::class, 'ALTER TABLE "t" ALTER COLUMN "id" SET CACHE 20'])]
