<?php

declare(strict_types=1);

namespace Tests\Unit\Binding\Schema;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Medium;
use PHPUnit\Framework\Attributes\TestWith;
use PHPUnit\Framework\TestCase;
use SqlSemantics\Binder;
use SqlSemantics\Dialect;
use SqlSemantics\InvalidSql;
use SqlSemantics\Model\Definition\Relation\Identity;
use SqlSemantics\Model\Statement\CreateTableStatement;
use SqlSemantics\Model\Validation\InputViolation;
use SqlSemantics\Schema\Column\IdentityColumn;
use SqlSemantics\SchemaBuilder;

#[CoversClass(\SqlSemantics\Binding\Schema\SequenceBinding::class)]
#[Medium]
final class SequenceBindingTest extends TestCase
{
    public function testReadClassifiesEveryAttribute(): void
    {
        $column = (new SchemaBuilder(Dialect::PostgreSql))->build('CREATE TABLE s(id INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 5 INCREMENT BY 2 MINVALUE 1 MAXVALUE 100 CACHE 3 NO CYCLE))')->tables[0]->columns[0];
        self::assertInstanceOf(IdentityColumn::class, $column->generation);
        $sequence = $column->generation->sequence;
        self::assertSame('5', $sequence->start?->text);
        self::assertSame('2', $sequence->increment?->text);
        self::assertSame('1', $sequence->minimum?->text);
        self::assertSame('100', $sequence->maximum?->text);
        self::assertSame('3', $sequence->cache?->text);
        self::assertFalse($sequence->cycle);
    }

    public function testReadLeavesOmittedAttributesNull(): void
    {
        $column = (new SchemaBuilder(Dialect::PostgreSql))->build('CREATE TABLE s(id INTEGER GENERATED BY DEFAULT AS IDENTITY (CYCLE))')->tables[0]->columns[0];
        self::assertInstanceOf(IdentityColumn::class, $column->generation);
        $sequence = $column->generation->sequence;
        self::assertNull($sequence->start);
        self::assertNull($sequence->increment);
        self::assertNull($sequence->minimum);
        self::assertNull($sequence->maximum);
        self::assertNull($sequence->cache);
        self::assertTrue($sequence->cycle);
        $plain = (new SchemaBuilder(Dialect::PostgreSql))->build('CREATE TABLE s(id INTEGER GENERATED ALWAYS AS IDENTITY)')->tables[0]->columns[0];
        self::assertInstanceOf(IdentityColumn::class, $plain->generation);
        self::assertNull($plain->generation->sequence->cycle);
    }

    public function testReadKeepsTheSignOfNegativeAndExplicitlyPositiveValues(): void
    {
        $binder = new Binder((new SchemaBuilder(Dialect::PostgreSql))->build());
        $statement = $binder->bind('CREATE TABLE s(id INTEGER GENERATED ALWAYS AS IDENTITY (START WITH -5 INCREMENT BY -2 MINVALUE -10 MAXVALUE +20))');
        self::assertInstanceOf(CreateTableStatement::class, $statement);
        $generation = $statement->definition->table->columns[0]->generation;
        self::assertInstanceOf(IdentityColumn::class, $generation);
        self::assertSame(['-5', '-2', '-10', '+20'], [$generation->sequence->start?->text, $generation->sequence->increment?->text, $generation->sequence->minimum?->text, $generation->sequence->maximum?->text]);
        self::assertSame('CREATE TABLE "public"."s"("id" integer NOT NULL GENERATED ALWAYS AS IDENTITY(START WITH -5 INCREMENT BY -2 MINVALUE -10 MAXVALUE +20))', (new \SqlSemantics\SimpleSerializer())->serialize($statement));
        self::assertSame((new \SqlSemantics\SimpleSerializer())->serialize($statement), (new \SqlSemantics\SimpleSerializer())->serialize($binder->bind((new \SqlSemantics\SimpleSerializer())->serialize($statement))));
    }

    public function testReadClassifiesNamingStoragePersistenceOwnershipAndRestart(): void
    {
        $binder = new Binder((new SchemaBuilder(Dialect::PostgreSql))->build());
        $statement = $binder->bind('CREATE TABLE s(id BIGINT GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME app.s_seq AS int8 UNLOGGED OWNED BY NONE RESTART 7 NO MAXVALUE))');
        self::assertInstanceOf(CreateTableStatement::class, $statement);
        $generation = $statement->definition->table->columns[0]->generation;
        self::assertInstanceOf(IdentityColumn::class, $generation);
        $sequence = $generation->sequence;
        self::assertSame(['app', 's_seq'], $sequence->name?->parts);
        self::assertSame('bigint', $sequence->storage?->name);
        self::assertFalse($sequence->logged);
        self::assertNull($sequence->owner?->column);
        self::assertSame('7', $sequence->restart?->value?->text);
        self::assertNull($sequence->maximum);
        self::assertSame('CREATE TABLE "public"."s"("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY(SEQUENCE NAME "app"."s_seq" AS bigint UNLOGGED OWNED BY NONE RESTART WITH 7))', (new \SqlSemantics\SimpleSerializer())->serialize($statement));
        self::assertSame((new \SqlSemantics\SimpleSerializer())->serialize($statement), (new \SqlSemantics\SimpleSerializer())->serialize($binder->bind((new \SqlSemantics\SimpleSerializer())->serialize($statement))));
    }

    #[TestWith(['START WITH 1 START 2', InputViolation::SequenceOption])]
    #[TestWith(['MINVALUE 1 NO MINVALUE', InputViolation::SequenceOption])]
    #[TestWith(['LOGGED UNLOGGED', InputViolation::SequenceOption])]
    #[TestWith(['AS text', InputViolation::SequenceOption])]
    #[TestWith(['CACHE 1.5', InputViolation::SequenceAttribute])]
    public function testReadDiagnosesConflictingAndNonIntegerOptions(string $options, InputViolation $violation): void
    {
        try {
            (new Binder((new SchemaBuilder(Dialect::PostgreSql))->build()))->bind('CREATE TABLE s(id INTEGER GENERATED ALWAYS AS IDENTITY (' . $options . '))');
            self::fail('The options must be diagnosed.');
        } catch (InvalidSql $error) {
            self::assertSame($violation, $error->violation);
        }
    }

    public function testKeyGroupsOptionsThatSetTheSameParameter(): void
    {
        self::assertSame('MinValue', \SqlSemantics\Binding\Schema\SequenceBinding::key(Identity\SequenceFlag::NoMinValue));
        self::assertSame('cycle', \SqlSemantics\Binding\Schema\SequenceBinding::key(Identity\SequenceFlag::NoCycle));
        self::assertSame('logged', \SqlSemantics\Binding\Schema\SequenceBinding::key(Identity\SequenceFlag::Unlogged));
        self::assertSame('owner', \SqlSemantics\Binding\Schema\SequenceBinding::key(new Identity\SetSequenceOwner(null)));
        self::assertSame('restart', \SqlSemantics\Binding\Schema\SequenceBinding::key(new Identity\RestartIdentity(null)));
    }

    public function testOptionsTreatsUnboundedLimitsAsDefaults(): void
    {
        $options = \SqlSemantics\Binding\Schema\SequenceBinding::options(['MinValue' => Identity\SequenceFlag::NoMinValue, 'cycle' => Identity\SequenceFlag::Cycle, 'logged' => Identity\SequenceFlag::Logged]);
        self::assertNull($options->minimum);
        self::assertTrue($options->cycle);
        self::assertTrue($options->logged);
        self::assertNull($options->storage);
    }
}
