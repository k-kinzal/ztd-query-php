<?php

declare(strict_types=1);

namespace Tests\Unit\Binding\Schema\Copy;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\Medium;
use PHPUnit\Framework\Attributes\TestWith;
use PHPUnit\Framework\TestCase;
use SqlSemantics\Ast\DialectParser;
use SqlSemantics\Ast\Identifiers;
use SqlSemantics\Ast\Tree;
use SqlSemantics\Binding\Schema\Copy\TemplateOptions;
use SqlSemantics\Binding\TableResolver;
use SqlSemantics\Dialect;
use SqlSemantics\Model\Definition\Relation\Foreign\TemplateProperty;
use SqlSemantics\Schema\Column;
use SqlSemantics\Schema\ColumnDefinition;
use SqlSemantics\Schema\IndexDefinition;
use SqlSemantics\Schema\TableConstraint;
use SqlSemantics\SchemaBuilder;
use SqlSemantics\Serialization\Expressions;

#[CoversClass(TemplateOptions::class)]
#[Medium]
final class TemplateOptionsTest extends TestCase
{
    /**
     * @param list<string> $expected
     */
    #[TestWith(['LIKE t', []])]
    #[TestWith(['LIKE t INCLUDING DEFAULTS INCLUDING INDEXES', ['DEFAULTS', 'INDEXES']])]
    #[TestWith(['LIKE t INCLUDING ALL EXCLUDING INDEXES EXCLUDING DEFAULTS', ['COMMENTS', 'COMPRESSION', 'CONSTRAINTS', 'IDENTITY', 'GENERATED', 'STATISTICS', 'STORAGE', 'ALL']])]
    #[TestWith(['LIKE t EXCLUDING ALL INCLUDING STORAGE', ['STORAGE']])]
    public function testIncludedAppliesTheOptionsInOrder(string $like, array $expected): void
    {
        $schema = (new SchemaBuilder(Dialect::PostgreSql))->build('CREATE TABLE t (a int)');
        $clause = Tree::outer((new DialectParser(Dialect::PostgreSql))->parse('CREATE TABLE u (' . $like . ')'), ['TableLikeClause'])[0];
        self::assertSame($expected, array_map(static fn (TemplateProperty $property): string => $property->value, TemplateOptions::included($clause, new TableResolver($schema, new Identifiers(Dialect::PostgreSql), 'public'))));
    }

    public function testColumnCopiesWhatTheOptionsInclude(): void
    {
        $tables = (new SchemaBuilder(Dialect::PostgreSql, grammarVersion: 'pg-17.2'))->build(
            'CREATE TABLE t (a serial PRIMARY KEY, b int DEFAULT 5 CHECK (b > 0), c int GENERATED ALWAYS AS (b * 2) STORED, d int GENERATED BY DEFAULT AS IDENTITY, e text STORAGE EXTERNAL COMPRESSION pglz COLLATE "C" UNIQUE, f int NOT NULL)',
            'CREATE TABLE u1 (LIKE t)',
            'CREATE TABLE u2 (LIKE t INCLUDING ALL)',
            'CREATE TABLE u3 (LIKE t INCLUDING ALL EXCLUDING INDEXES EXCLUDING DEFAULTS)',
            'CREATE TABLE u4 (LIKE t INCLUDING DEFAULTS INCLUDING INDEXES)',
        )->tables;
        $describe = static fn (ColumnDefinition $column): string => $column->name . ' ' . $column->nullability->value . ' ' . ($column->generation instanceof Column\SuppliedColumn ? ($column->generation->default === null ? '-' : Expressions::write($column->generation->default)->toString()) : basename(str_replace('\\', '/', $column->generation::class))) . ' ' . ($column->attributes->collation?->parts[0] ?? '-') . ' ' . ($column->attributes->compression ?? '-') . ' ' . ($column->attributes->storageStrategy->value ?? '-');
        self::assertSame(['a not-null - - - -', 'b maybe-null - - - -', 'c maybe-null - - - -', 'd not-null - - - -', 'e maybe-null - C - -', 'f not-null - - - -'], array_map($describe, $tables[1]->columns));
        self::assertSame(['a not-null "nextval"(CAST(\'t_a_seq\' AS "regclass")) - - -', 'b maybe-null 5 - - -', 'c maybe-null ComputedColumn - - -', 'd not-null IdentityColumn - - -', 'e maybe-null - C pglz EXTERNAL', 'f not-null - - - -'], array_map($describe, $tables[2]->columns));
        self::assertSame(['a not-null - - - -', 'b maybe-null - - - -', 'c maybe-null ComputedColumn - - -', 'd not-null IdentityColumn - - -', 'e maybe-null - C pglz EXTERNAL', 'f not-null - - - -'], array_map($describe, $tables[3]->columns));
        self::assertSame(['a not-null "nextval"(CAST(\'t_a_seq\' AS "regclass")) - - -', 'b maybe-null 5 - - -', 'c maybe-null - - - -', 'd not-null - - - -', 'e maybe-null - C - -', 'f not-null - - - -'], array_map($describe, $tables[4]->columns));
    }

    public function testConstraintsCopiesChecksAndRenamedKeysOnlyWhenIncluded(): void
    {
        $tables = (new SchemaBuilder(Dialect::PostgreSql, grammarVersion: 'pg-17.2'))->build(
            'CREATE TABLE t (a int PRIMARY KEY, b int CONSTRAINT positive CHECK (b > 0) NO INHERIT, c int REFERENCES t (a))',
            'CREATE INDEX ON t (b)',
            'CREATE TABLE u1 (LIKE t INCLUDING CONSTRAINTS)',
            'CREATE TABLE u2 (LIKE t INCLUDING INDEXES)',
            'CREATE TABLE u3 (LIKE t)',
        )->tables;
        $names = static fn (TableConstraint $constraint): ?string => $constraint->name;
        self::assertSame([['positive'], ['u2_pkey'], []], [array_map($names, $tables[1]->constraints), array_map($names, $tables[2]->constraints), array_map($names, $tables[3]->constraints)]);
        self::assertSame([[], ['u2_b_idx'], []], [array_map(static fn (IndexDefinition $index): ?string => $index->name, $tables[1]->indexes), array_map(static fn (IndexDefinition $index): ?string => $index->name, $tables[2]->indexes), $tables[3]->indexes]);
        self::assertSame(['public', 'u2'], $tables[2]->indexes[0]->table);
        self::assertCount(0, TemplateOptions::constraints($tables[0]->constraints, []));
    }

    public function testSequenceDefaultDrawsFromTheTemplateSequence(): void
    {
        $schema = (new SchemaBuilder(Dialect::PostgreSql, grammarVersion: 'pg-17.2'))->build('CREATE TABLE app."T" (a serial)');
        $generation = TemplateOptions::sequenceDefault($schema->tables[0]->columns[0], $schema->tables[0], new TableResolver($schema, new Identifiers(Dialect::PostgreSql), 'public'));
        self::assertInstanceOf(Column\SuppliedColumn::class, $generation);
        self::assertNotNull($generation->default);
        self::assertSame('"nextval"(CAST(\'app."T_a_seq"\' AS "regclass"))', Expressions::write($generation->default)->toString());
    }
}
