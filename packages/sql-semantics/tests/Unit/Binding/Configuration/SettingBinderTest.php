final class SettingBinderTest extends TestCase
{
    public function testBindRetainsScopeNameAndValue(): void
    {
        $statement = (new Binder((new SchemaBuilder(Dialect::PostgreSql))->build()))->bind("SET LOCAL work_mem='64MB'");
        self::assertSame(['work_mem'], $statement->settings[0]->name);
        self::assertSame('local', $statement->settings[0]->scope);
        self::assertSame("'64MB'", $statement->settings[0]->values[0]->symbol);
    }
    public function testSettingPreservesMysqlAssignmentOrderAndScopes(): void
    {
        $statement = (new Binder((new SchemaBuilder(Dialect::MySql))->build()))->bind("SET SESSION sql_mode='ANSI', @n=1, @@GLOBAL.max_connections=200");
        self::assertSame([['sql_mode'], ['n'], ['max_connections']], array_column($statement->settings, 'name'));
        self::assertSame(['session', 'user', 'global'], array_column($statement->settings, 'scope'));
    }
    public function testMakeKeepsValueListsAndDefault(): void
    {
        $binder = new Binder((new SchemaBuilder(Dialect::PostgreSql))->build());
        $statement = $binder->bind('SET search_path TO public, example');
        self::assertSame(['public','example'], array_column($statement->settings[0]->values, 'symbol'));
        self::assertSame('default', $binder->bind('SET work_mem TO DEFAULT')->settings[0]->values[0]->kind->value);
        self::assertSame('from-current', $binder->bind('SET work_mem FROM CURRENT')->settings[0]->action);
        self::assertSame(['*'], $binder->bind('RESET ALL')->settings[0]->name);
    }
    public function testPragmaRetainsQualifiedNameAndReadMode(): void
    {
        $binder = new Binder((new SchemaBuilder(Dialect::Sqlite))->build());
        $statement = $binder->bind('PRAGMA main.cache_size=-2000');
        self::assertSame(['main','cache_size'], $statement->settings[0]->name);
        self::assertSame('database', $statement->settings[0]->scope);
        self::assertSame('set', $statement->settings[0]->action);
        self::assertSame('read', $binder->bind('PRAGMA cache_size')->settings[0]->action);
    }

    public function testScopeNormalizesMysqlLocalWithoutDroppingQualifiedNames(): void
    {
        $binder = new Binder((new SchemaBuilder(Dialect::MySql))->build());
        self::assertSame('session', $binder->bind('SET LOCAL sql_mode=DEFAULT')->settings[0]->scope);
        self::assertSame(['component','variable'], $binder->bind('SET @@component.variable=1')->settings[0]->name);
    }
    public function testSettingResetsPersistedVariablesWithoutRequiringAName(): void
    {
        $binder = new Binder((new SchemaBuilder(Dialect::MySql))->build());
        $all = $binder->bind('RESET PERSIST')->settings[0];
        self::assertSame(['*'], $all->name);
        self::assertSame('persist', $all->scope);
        self::assertSame('reset', $all->action);
        self::assertFalse($all->ifExists);
        $named = $binder->bind('RESET PERSIST IF EXISTS max_connections')->settings[0];
        self::assertSame(['max_connections'], $named->name);
        self::assertTrue($named->ifExists);
    }

    public function testBindHandlesLowercaseVariablesAndScopedNames(): void
    {
        $binder = new Binder((new SchemaBuilder(Dialect::MySql))->build());
        $statement = $binder->bind("set @@local.sql_mode='ANSI', @x:=2, persist_only.max_connections=3");
        self::assertSame(['session','user','session'], array_column($statement->settings, 'scope'));
        self::assertSame([['sql_mode'],['x'],['persist_only','max_connections']], array_column($statement->settings, 'name'));
        self::assertSame('2', $statement->settings[1]->values[0]->symbol);
    }
    public function testPragmaRetainsParenthesizedValue(): void
    {
        $setting = (new Binder((new SchemaBuilder(Dialect::Sqlite))->build()))->bind('pragma main.cache_size(-2000);')->settings[0];
        self::assertSame(['main','cache_size'], $setting->name);
        self::assertSame('set', $setting->action);
        self::assertCount(1, $setting->values);
        self::assertSame('-', $setting->values[0]->symbol);
        self::assertSame('2000', $setting->values[0]->operands[0]->symbol);
    }
}
