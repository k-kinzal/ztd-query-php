<?php

declare(strict_types=1);

require __DIR__ . '/server_connection.php';

[$pdo, $environment] = connectFixture('postgres');
if ($pdo->query('SELECT current_database()')->fetchColumn() !== 'ir_fixture') {
    throw new RuntimeException('The truncation observer requires the disposable ir_fixture database.');
}

function resetTruncateFixture(PDO $pdo, string $fixture): void
{
    $pdo->exec('DROP SCHEMA IF EXISTS ir_tr_decoy CASCADE');
    $pdo->exec('DROP TABLE IF EXISTS public.ir_tr_a, public.ir_tr_b, public.ir_tr_child, public.ir_tr_ref, public.ir_tr_leaf, public.ir_tr_events, public.ir_tr_marker CASCADE');
    $pdo->exec('DROP SEQUENCE IF EXISTS public.ir_tr_unowned');
    $pdo->exec('CREATE SEQUENCE public.ir_tr_unowned START WITH 71');
    $pdo->query("SELECT nextval('public.ir_tr_unowned')")->fetchColumn();
    $pdo->exec('CREATE SCHEMA ir_tr_decoy');
    $pdo->exec('CREATE TABLE public.ir_tr_a (id int GENERATED BY DEFAULT AS IDENTITY (START WITH 11) PRIMARY KEY,label text)');
    $pdo->exec('CREATE TABLE public.ir_tr_b (id int GENERATED BY DEFAULT AS IDENTITY (START WITH 21) PRIMARY KEY,label text)');
    $pdo->exec('CREATE TABLE ir_tr_decoy.ir_tr_a (id int GENERATED BY DEFAULT AS IDENTITY (START WITH 81) PRIMARY KEY,label text)');
    $pdo->exec("INSERT INTO public.ir_tr_a (label) VALUES ('dup'),('dup')");
    $pdo->exec("INSERT INTO public.ir_tr_b (label) VALUES (NULL),('second')");
    $pdo->exec("INSERT INTO ir_tr_decoy.ir_tr_a (label) VALUES ('decoy')");
    $pdo->exec('CREATE TABLE public.ir_tr_events (ordinal integer, schema_name text, table_name text, phase text, action text)');
    $pdo->exec('CREATE TABLE public.ir_tr_marker (step integer)');
    $pdo->exec('INSERT INTO public.ir_tr_marker VALUES (0)');
    $targets = ['public.ir_tr_a', 'public.ir_tr_b', 'ir_tr_decoy.ir_tr_a'];
    if ($fixture === 'dependent') {
        $pdo->exec('CREATE TABLE public.ir_tr_child (note text) INHERITS (public.ir_tr_a)');
        $pdo->exec('CREATE TABLE public.ir_tr_ref (id int GENERATED BY DEFAULT AS IDENTITY (START WITH 31) PRIMARY KEY,pid int REFERENCES public.ir_tr_a(id))');
        $pdo->exec('CREATE TABLE public.ir_tr_leaf (id int GENERATED BY DEFAULT AS IDENTITY (START WITH 41) PRIMARY KEY,rid int REFERENCES public.ir_tr_ref(id))');
        $pdo->exec("INSERT INTO public.ir_tr_child VALUES (99,'inherit','child')");
        $pdo->exec('INSERT INTO public.ir_tr_ref(pid) VALUES (11)');
        $pdo->exec('INSERT INTO public.ir_tr_leaf(rid) VALUES (31)');
        array_push($targets, 'public.ir_tr_child', 'public.ir_tr_ref', 'public.ir_tr_leaf');
    }
    $pdo->exec(<<<'SQL'
        CREATE OR REPLACE FUNCTION public.ir_tr_logging() RETURNS trigger LANGUAGE plpgsql AS $routine$
        BEGIN
            INSERT INTO public.ir_tr_events
                SELECT count(*) + 1, TG_TABLE_SCHEMA, TG_TABLE_NAME, TG_WHEN, TG_OP FROM public.ir_tr_events;
            RETURN NULL;
        END
        $routine$
        SQL);
    foreach ($targets as $table) {
        foreach (['BEFORE TRUNCATE', 'AFTER TRUNCATE', 'AFTER DELETE'] as $action) {
            $key = str_replace(' ', '_', strtolower($action));
            $pdo->exec("CREATE TRIGGER $key $action ON $table FOR EACH STATEMENT EXECUTE FUNCTION public.ir_tr_logging()");
        }
    }
}

function observedTruncateState(PDO $pdo): array
{
    $records = $pdo->query(<<<'SQL'
        SELECT c.oid, n.nspname, c.relname
        FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
        WHERE c.relkind = 'r' AND n.nspname IN ('public', 'ir_tr_decoy')
        AND c.relname IN ('ir_tr_a', 'ir_tr_b', 'ir_tr_child', 'ir_tr_ref', 'ir_tr_leaf')
        ORDER BY n.nspname, c.relname
        SQL)->fetchAll(PDO::FETCH_NUM);
    $data = [];
    $sequences = ['public.ir_tr_unowned' => $pdo->query('SELECT last_value,is_called FROM public.ir_tr_unowned')->fetch(PDO::FETCH_NUM)];
    foreach ($records as [$oid, $schema, $table]) {
        $qualified = $schema . '.' . $table;
        $data[$qualified] = [
            'oid' => (int) $oid,
            'fields' => $pdo->query('SELECT a.attname,t.typname,CAST(t.oid AS integer),a.attnotnull'
                . ' FROM pg_catalog.pg_attribute a JOIN pg_catalog.pg_type t ON a.atttypid=t.oid'
                . ' WHERE a.attrelid=' . (int) $oid . ' AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum')->fetchAll(PDO::FETCH_NUM),
            'rows' => $pdo->query('SELECT * FROM ONLY ' . $qualified)->fetchAll(PDO::FETCH_NUM),
        ];
        if ($table !== 'ir_tr_child') {
            $owned = $qualified . '_id_seq';
            $sequences[$owned] = $pdo->query('SELECT last_value,is_called FROM ' . $owned)->fetch(PDO::FETCH_NUM);
        }
    }
    return [
        'tables' => $data, 'sequences' => $sequences,
        'events' => $pdo->query('SELECT schema_name,table_name,phase,action FROM public.ir_tr_events ORDER BY ordinal')->fetchAll(PDO::FETCH_NUM),
        'marker' => $pdo->query('SELECT step FROM public.ir_tr_marker ORDER BY step')->fetchAll(PDO::FETCH_COLUMN),
    ];
}

function observePostgresTruncate(PDO $pdo, array $request): array
{
    $namespace = '(?:"public"|"ir_tr_decoy"|public|ir_tr_decoy)';
    $name = '(?:ir_tr_(?:a|b|child|ref|leaf|absent)|"ir_tr_(?:a|b|child|ref|leaf|absent)")';
    $target = '(?:ONLY )?(?:' . $namespace . '\.)?' . $name . '(?: \*)?';
    $pattern = '/\ATRUNCATE(?: TABLE)? ' . $target . '(?:, ' . $target . '){0,9}(?: (?:RESTART|CONTINUE) IDENTITY)?(?: CASCADE| RESTRICT)?\z/D';
    $fixture = $request['fixture'];
    $sql = $request['sql'];
    if (preg_match($pattern, $sql) !== 1 || !in_array($fixture, ['plain', 'dependent'], true)) {
        return ['status' => 'outside-observer-scope'];
    }
    resetTruncateFixture($pdo, $fixture);
    $original = observedTruncateState($pdo);
    $pdo->beginTransaction();
    $pdo->exec('SET LOCAL search_path = public');
    $profile = $pdo->query("SELECT json_build_array(current_schema()::text,current_setting('search_path'),current_schemas(true)::text[])")->fetchColumn();
    $pdo->exec('INSERT INTO public.ir_tr_marker VALUES (7)');
    $pdo->exec('SAVEPOINT ir_tr_effect');
    try {
        $pdo->exec($sql);
        $effect = ['executed'];
    } catch (PDOException $error) {
        $effect = ['db-error', $error->errorInfo[0]];
        $pdo->exec('ROLLBACK TO SAVEPOINT ir_tr_effect');
    }
    $after = observedTruncateState($pdo);
    $active = $pdo->inTransaction();
    $pdo->rollBack();

    return [
        'status' => 'postgres-truncate-effect', 'namespace' => json_decode($profile, true, 512, JSON_THROW_ON_ERROR),
        'original' => $original, 'effect' => $effect, 'after' => $after, 'active' => $active, 'restored' => observedTruncateState($pdo),
    ];
}

resetTruncateFixture($pdo, 'dependent');
echo json_encode(['database' => $environment, 'php' => PHP_VERSION, 'initial' => observedTruncateState($pdo)], JSON_THROW_ON_ERROR) . "\n";
while (($line = fgets(STDIN)) !== false) {
    $request = json_decode($line, true, 512, JSON_THROW_ON_ERROR);
    $batch = array_is_list($request);
    $results = array_map(static fn (array $item): array => observePostgresTruncate($pdo, $item), $batch ? $request : [$request]);
    echo json_encode($batch ? $results : $results[0], JSON_THROW_ON_ERROR) . "\n";
}
