@lru_cache(maxsize=None)
def release_subset(domain):
    field = {
        "mysql_with_projection": "profiles",
        "mysql_index_rename": "releases",
        "mysql_mixed_index_alteration": "releases",
        "mysql_index_foreign_keys": "releases",
        "mysql_implicit_foreign_indexes": "releases",
        "mysql_drop_foreign_keys": "releases",
        "mysql_add_foreign_keys": "releases",
        "mysql_foreign_key_strings": "releases",
        "mysql_foreign_key_scalars": "releases",
        "mysql_index_visibility": "releases",
    }.get(domain)
    if field is None:
        return None
    path = NATIVE[domain]
    contract = (TOOL / path).read_bytes()
    if hashlib.sha256(contract).hexdigest() != CONTRACTS[path]:
        raise ValueError(f"The native release scope for {domain} has changed")
    return tuple(tag.removeprefix("mysql-") for tag in json.loads(contract)[field])


def reports(raw, layout, domain):
    if layout == "release":
        for engine in ("mysql", "postgres"):
            yield from sorted(raw.glob(f"{engine}-*/{domain}/index.json"))
        return
    prefix = "semantics-ir" if domain == "projection" else f"native-{domain.replace('_', '-')}"
    for engine in ("mysql", "postgres"):
        yield from sorted(raw.glob(f"{prefix}-{engine}-*/index.json"))
