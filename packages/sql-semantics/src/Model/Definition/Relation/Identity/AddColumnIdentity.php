<?php

declare(strict_types=1);

namespace SqlSemantics\Model\Definition\Relation\Identity;

use SqlSemantics\Model\Definition\Catalog\CatalogInvariant;
use SqlSemantics\Model\Definition\RelationAction;
use SqlSemantics\Model\Validation\Collections;
use SqlSemantics\Model\Validation\InvalidStructure;
use SqlSemantics\Schema\Column\IdentityMode;

/**
 * Turns one column into an identity column backed by a new sequence with the given options.
 * @visibility public
 * @example Reading the identity mode and options
 *     $statement = (new \SqlSemantics\Binder((new \SqlSemantics\SchemaBuilder(\SqlSemantics\Dialect::PostgreSql))->build('CREATE TABLE t(id INTEGER)')))->bind('ALTER TABLE t ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 10 NO CYCLE)');
 *     $statement->actions[0]->mode // => \SqlSemantics\Schema\Column\IdentityMode::ByDefault
 *     $statement->actions[0]->options[1] // => \SqlSemantics\Model\Definition\Relation\Identity\SequenceFlag::NoCycle
 */
final class AddColumnIdentity implements RelationAction
{
    /**
     * @param list<SequenceValueChange|SequenceFlag|SetSequenceName|SequenceStorage|SetSequenceOwner|RestartIdentity> $options
     * @throws InvalidStructure
     */
    public function __construct(public readonly string $column, public readonly IdentityMode $mode, public readonly array $options = [])
    {
        CatalogInvariant::identifier($column);
        Collections::alternatives($options, [SequenceValueChange::class, SequenceFlag::class, SetSequenceName::class, SequenceStorage::class, SetSequenceOwner::class, RestartIdentity::class]);
    }
}
