<?php

declare(strict_types=1);

namespace SqlSemantics\Schema\Column;

/**
 * Sequence attributes; omitted attributes use database defaults.
 * NO MINVALUE and NO MAXVALUE request the default bounds and are therefore recorded as omitted bounds.
 *
 * @visibility public
 * @example Reading declared sequence attributes
 *     $column = (new \SqlSemantics\SchemaBuilder(\SqlSemantics\Dialect::PostgreSql))->build('CREATE TABLE t(id INTEGER GENERATED ALWAYS AS IDENTITY (MINVALUE 1 MAXVALUE 100 CACHE 3 CYCLE))')->tables[0]->columns[0];
 *     $column->generation->sequence->maximum->text // => '100'
 *     $column->generation->sequence->cache->text // => '3'
 *     $column->generation->sequence->cycle // => true
 *     $column->generation->sequence->start // => null
 *     $named = (new \SqlSemantics\SchemaBuilder(\SqlSemantics\Dialect::PostgreSql))->build('CREATE TABLE t(id BIGINT GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME t_seq AS bigint MINVALUE -3 UNLOGGED))')->tables[0]->columns[0];
 *     $named->generation->sequence->name->parts // => ['t_seq']
 *     $named->generation->sequence->storage->name // => 'bigint'
 *     $named->generation->sequence->minimum->text // => '-3'
 *     $named->generation->sequence->logged // => false
 */
final class SequenceOptions
{
    /**
     * Constructs a valid declaration.
     * @param \SqlSemantics\Type\TypeDescriptor|null $storage Integer type of the sequence (AS)
     * @param \SqlSemantics\Model\Relation\QualifiedName|null $name Sequence name (SEQUENCE NAME)
     * @param bool|null $logged Persistence of the sequence (LOGGED or UNLOGGED)
     * @param \SqlSemantics\Model\Definition\Relation\Identity\SetSequenceOwner|null $owner Owning column or NONE (OWNED BY)
     * @param \SqlSemantics\Model\Definition\Relation\Identity\RestartIdentity|null $restart Initial current value (RESTART)
     * @throws \SqlSemantics\Model\Validation\InvalidStructure
     */
    public function __construct(
        public readonly ?\SqlSemantics\Model\Scalar\Value\Literal $start = null,
        public readonly ?\SqlSemantics\Model\Scalar\Value\Literal $increment = null,
        public readonly ?\SqlSemantics\Model\Scalar\Value\Literal $minimum = null,
        public readonly ?\SqlSemantics\Model\Scalar\Value\Literal $maximum = null,
        public readonly ?\SqlSemantics\Model\Scalar\Value\Literal $cache = null,
        public readonly ?bool $cycle = null,
        public readonly ?\SqlSemantics\Type\TypeDescriptor $storage = null,
        public readonly ?\SqlSemantics\Model\Relation\QualifiedName $name = null,
        public readonly ?bool $logged = null,
        public readonly ?\SqlSemantics\Model\Definition\Relation\Identity\SetSequenceOwner $owner = null,
        public readonly ?\SqlSemantics\Model\Definition\Relation\Identity\RestartIdentity $restart = null,
    ) {
        foreach ([$start, $increment, $minimum, $maximum, $cache] as $number) {
            if ($number !== null && preg_match('/^[+-]?[0-9]+$/D', $number->text) !== 1) {
                throw new \SqlSemantics\Model\Validation\InvalidStructure('A sequence attribute must be an integer literal.');
            }
        }
        if ($storage !== null && !in_array($storage->name, ['smallint', 'integer', 'bigint'], true)) {
            throw new \SqlSemantics\Model\Validation\InvalidStructure('A sequence type must be smallint, integer, or bigint.');
        }
        if ($name !== null) {
            \SqlSemantics\Model\Definition\Catalog\CatalogInvariant::name($name, 3);
        }
    }
}
