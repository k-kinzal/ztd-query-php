<?php

/**
 * Samples WEIGHT_STRING declared capacity from public PDO result metadata on MySQL 8.4.7.
 *
 * Usage: php bin/weight-lengths.php <dsn> <user> <password> > resources/weight-lengths.php
 */

declare(strict_types=1);

$pdo = new PDO($argv[1], $argv[2], $argv[3], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$rows = [];
foreach ($pdo->query('SELECT COLLATION_NAME, CHARACTER_SET_NAME FROM information_schema.COLLATIONS ORDER BY COLLATION_NAME')->fetchAll(PDO::FETCH_NUM) as [$collation, $charset]) {
    $lengths = [];
    foreach ([16, 32] as $count) {
        $collated = '`' . str_replace('`', '``', (string) $collation) . '`';
        $encoding = '`' . str_replace('`', '``', (string) $charset) . '`';
        $operand = $charset === 'binary' ? "REPEAT(_binary'a', $count)" : "CONVERT(REPEAT('a', $count) USING $encoding)";
        $result = $pdo->query("SELECT WEIGHT_STRING($operand COLLATE $collated)");
        $lengths[] = $result->getColumnMeta(0)['len'];
        $result->closeCursor();
    }
    [$short, $long] = $lengths;
    if (($long - $short) % 16 !== 0) {
        throw new RuntimeException('The sampled result length must have an integral expansion.');
    }
    $rows[] = sprintf('    %s => [%d, %d],', var_export((string) $collation, true), intdiv($long - $short, 16), 2 * $short - $long);
}
echo "<?php\n\n/**\n * WEIGHT_STRING result byte lengths: collation => [bytes per input character, overhead].\n *\n * Generated by bin/weight-lengths.php from PDO metadata on MySQL 8.4.7.\n * Samples use CONVERT(REPEAT('a', n) USING charset) COLLATE collation for\n * n=16 and n=32. These are declared capacities, not evaluated weight lengths.\n * No server source was used.\n */\n\ndeclare(strict_types=1);\n\nreturn [\n" . implode("\n", $rows) . "\n];\n";
