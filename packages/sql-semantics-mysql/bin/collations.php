<?php

/**
 * Writes the character set and collation catalog of one MySQL release from a running server of that release.
 *
 * Usage: php bin/collations.php <dsn> <user> <password> > resources/collations/mysql-<release>.php
 */

declare(strict_types=1);

$pdo = new PDO($argv[1], $argv[2], $argv[3], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$pad = (int) $pdo->query("SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = 'information_schema' AND TABLE_NAME = 'COLLATIONS' AND COLUMN_NAME = 'PAD_ATTRIBUTE'")->fetchColumn() > 0;
$charsets = [];
foreach ($pdo->query('SELECT CHARACTER_SET_NAME, DEFAULT_COLLATE_NAME, MAXLEN FROM information_schema.CHARACTER_SETS ORDER BY CHARACTER_SET_NAME')->fetchAll(PDO::FETCH_NUM) as [$name, $default, $length]) {
    $charsets[] = sprintf('        %s => [%s, %d],', var_export((string) $name, true), var_export((string) $default, true), (int) $length);
}
$collations = [];
$query = 'SELECT COLLATION_NAME, CHARACTER_SET_NAME, ID, ' . ($pad ? "PAD_ATTRIBUTE = 'PAD SPACE'" : '1') . ' FROM information_schema.COLLATIONS ORDER BY ID';
foreach ($pdo->query($query)->fetchAll(PDO::FETCH_NUM) as [$name, $charset, $id, $padSpace]) {
    $collations[] = sprintf('        %s => [%s, %d, %s],', var_export((string) $name, true), var_export((string) $charset, true), (int) $id, (int) $padSpace === 1 ? 'true' : 'false');
}
$version = $pdo->query('SELECT @@version')->fetchColumn();
echo "<?php\n\n/**\n * The character sets and collations of MySQL {$version}.\n *\n * Character sets: name => [default collation, maximum bytes per character].\n * Collations: name => [character set, id, whether PAD SPACE].\n * Generated by bin/collations.php from a server of the release.\n */\n\ndeclare(strict_types=1);\n\nreturn [\n    'charsets' => [\n" . implode("\n", $charsets) . "\n    ],\n    'collations' => [\n" . implode("\n", $collations) . "\n    ],\n];\n";
