<?php

/**
 * Writes the system variable catalog of one MySQL release from a running server of that release.
 *
 * Usage: php bin/variables.php <host> <port> <user> <password> > resources/variables/mysql-<release>.php
 * Run it against a disposable server: each variable is assigned its own value in each scope to
 * learn whether the scope is read-only.
 */

declare(strict_types=1);

$mysqli = new mysqli($argv[1], $argv[3], $argv[4], '', (int) $argv[2]);
$mysqli->set_charset('utf8mb4');
mysqli_report(MYSQLI_REPORT_OFF);
$rows = static fn (string $sql): array => ($result = $mysqli->query($sql)) instanceof mysqli_result ? $result->fetch_all(MYSQLI_NUM) : [];
$bounds = [];
foreach ($rows('SELECT VARIABLE_NAME, MIN_VALUE, MAX_VALUE FROM performance_schema.variables_info') as [$name, $minimum, $maximum]) {
    $bounds[strtolower((string) $name)] = [$minimum, $maximum];
}
$values = [];
foreach ([...$rows('SHOW SESSION VARIABLES'), ...$rows('SHOW GLOBAL VARIABLES')] as [$name, $value]) {
    $values[strtolower((string) $name)] ??= (string) $value;
}
ksort($values);
$entries = [];
foreach ($values as $name => $value) {
    $session = $mysqli->query("SELECT @@SESSION.`$name`") !== false;
    $global = $mysqli->query("SELECT @@GLOBAL.`$name`") !== false;
    if (!$session && !$global) {
        continue;
    }
    $sessionFixed = $session && !$mysqli->query("SET @@SESSION.`$name` = @@SESSION.`$name`") && in_array($mysqli->errno, [1238, 1621], true);
    $globalFixed = $global && !$mysqli->query("SET @@GLOBAL.`$name` = @@GLOBAL.`$name`") && $mysqli->errno === 1238;
    $readOnly = ($sessionFixed || !$session) && ($globalFixed || !$global) ? 'Yes' : ($sessionFixed ? 'Session' : 'No');
    $read = $session ? "@@SESSION.`$name`" : "@@GLOBAL.`$name`";
    $result = $mysqli->query("SELECT $read, COLLATION($read)");
    if (!$result instanceof mysqli_result) {
        continue;
    }
    $field = $result->fetch_fields()[0];
    $collation = (string) ($result->fetch_row()[1] ?? 'binary');
    [$minimum, $maximum] = $bounds[$name] ?? [null, null];
    $shape = match (true) {
        in_array($value, ['ON', 'OFF'], true) => 'Boolean',
        $minimum !== null && $maximum !== null && $maximum !== '0' && preg_match('/\A-?[0-9]+\z/', $value) === 1 => str_starts_with((string) $minimum, '-') ? 'Integer' : 'Unsigned',
        $minimum === null && in_array($field->type, [MYSQLI_TYPE_LONGLONG, MYSQLI_TYPE_LONG], true) && preg_match('/\A-?[0-9]+\z/', $value) === 1 => ($field->flags & MYSQLI_UNSIGNED_FLAG) !== 0 ? 'Unsigned' : 'Integer',
        $field->type === MYSQLI_TYPE_DOUBLE => 'Double',
        default => 'Text',
    };
    $scope = $session && $global ? 'Both' : ($session ? 'Session' : 'Global');
    $default = in_array($shape, ['Integer', 'Unsigned'], true) ? (int) $value : $value;
    $numeric = in_array($shape, ['Integer', 'Unsigned'], true);
    $length = $field->charsetnr === 63 ? $field->length : intdiv($field->length, 4);
    $entries[] = sprintf(
        "    [%s, '%s', '%s', %s, '%s', %s, %s, %d, %d, %d, %s, %s],",
        var_export($name, true),
        $scope,
        $shape,
        var_export($default, true),
        $readOnly,
        !$numeric || $minimum === null ? 'null' : ($minimum === '-9223372036854775808' ? 'PHP_INT_MIN' : $minimum),
        !$numeric || $maximum === null ? 'null' : (bccomp((string) $maximum, (string) PHP_INT_MAX) > 0 ? 'PHP_INT_MAX' : $maximum),
        $field->type,
        $length,
        $field->decimals,
        ($field->flags & MYSQLI_UNSIGNED_FLAG) !== 0 ? 'true' : 'false',
        var_export($collation, true),
    );
}
$version = $mysqli->query('SELECT @@version')->fetch_row()[0];
echo "<?php\n\n/**\n * The system variables of MySQL {$version}.\n *\n * Each entry: name, scope, shape, global value, which scopes are read-only, integer bounds, and how a read\n * is typed: field code, length in characters, decimals, whether unsigned, collation.\n * Generated by bin/variables.php from a server of the release.\n */\n\ndeclare(strict_types=1);\n\nreturn [\n" . implode("\n", $entries) . "\n];\n";
