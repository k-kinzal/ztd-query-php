<?php

/**
 * Writes the system table catalog of one MySQL release from a running server of that release.
 *
 * Usage: php bin/system-tables.php <host> <port> <user> <password> > resources/system-tables/mysql-<release>.php
 * Every table of information_schema, mysql and performance_schema is read without rows: the
 * metadata of its columns as a result reports them, with the base column each reads, the collation and coercibility of each, and
 * the column type, default, key and extra INFORMATION_SCHEMA.COLUMNS lists for it.
 */

declare(strict_types=1);

$mysqli = new mysqli($argv[1], $argv[3], $argv[4], '', (int) $argv[2]);
$mysqli->set_charset('utf8mb4');
mysqli_report(MYSQLI_REPORT_OFF);
$rows = static fn (string $sql): array => ($result = $mysqli->query($sql)) instanceof mysqli_result ? $result->fetch_all(MYSQLI_NUM) : [];
$quote = static fn (string $name): string => '`' . str_replace('`', '``', $name) . '`';
$text = static fn (mixed $value): string => $value === null ? 'null' : var_export((string) $value, true);
$tables = $rows("SELECT TABLE_SCHEMA, TABLE_NAME, TABLE_TYPE, ENGINE, VERSION, ROW_FORMAT, TABLE_COLLATION, CREATE_OPTIONS, TABLE_COMMENT FROM information_schema.TABLES WHERE TABLE_SCHEMA IN ('information_schema', 'mysql', 'performance_schema') ORDER BY TABLE_SCHEMA, TABLE_NAME");
$entries = [];
foreach ($tables as [$schema, $name, $type, $engine, $version, $format, $collation, $options, $comment]) {
    $result = $mysqli->query('SELECT * FROM ' . $quote($schema) . '.' . $quote($name) . ' LIMIT 0');
    if (!$result instanceof mysqli_result) {
        fwrite(STDERR, "skipped $schema.$name: {$mysqli->error}\n");
        continue;
    }
    $fields = $result->fetch_fields();
    $reads = [];
    foreach ($fields as $field) {
        $reads[] = 'COLLATION(t.' . $quote($field->name) . '), COERCIBILITY(t.' . $quote($field->name) . ')';
    }
    $collations = $rows('SELECT ' . implode(', ', $reads) . ' FROM (SELECT 1) d LEFT JOIN ' . $quote($schema) . '.' . $quote($name) . ' t ON FALSE')[0] ?? [];
    $declared = [];
    $query = "SELECT COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT, COLUMN_KEY, EXTRA, COLUMN_COMMENT, COLLATION_NAME FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = '" . $mysqli->real_escape_string($schema) . "' AND TABLE_NAME = '" . $mysqli->real_escape_string($name) . "' ORDER BY ORDINAL_POSITION";
    foreach ($rows($query) as $column) {
        $declared[strtolower((string) $column[0])] = $column;
    }
    $columns = [];
    foreach ($fields as $position => $field) {
        $chars = $field->charsetnr === 63 ? $field->length : ($field->length >= 4294967295 ? 4294967295 : intdiv($field->length, 4));
        $read = (string) ($collations[$position * 2] ?? 'binary');
        $coercibility = (int) ($collations[$position * 2 + 1] ?? 2);
        [, $columnType, $nullable, $default, $key, $extra, $columnComment, $declaredCollation] = $declared[strtolower($field->name)] ?? [null, '', 'YES', null, '', '', '', null];
        $columns[] = sprintf(
            '            [%s, %s, %s, %s, %d, %d, %d, %d, %s, %d, %s, %s, %s, %s, %s, %s, %s],',
            $text($field->name),
            $text($field->orgname),
            $text($field->orgtable),
            $text($field->db),
            $field->type,
            $chars,
            $field->decimals,
            $field->flags,
            $text($field->charsetnr === 63 && !in_array($field->type, [MYSQLI_TYPE_VAR_STRING, MYSQLI_TYPE_STRING, MYSQLI_TYPE_BLOB], true) ? 'binary' : ($read === 'binary' && $field->charsetnr !== 63 ? ($declaredCollation ?? 'utf8mb3_general_ci') : $read)),
            $coercibility,
            $text($columnType),
            $text($nullable),
            $text($default),
            $text($key),
            $text($extra),
            $text($columnComment),
            $text($declaredCollation),
        );
    }
    $entries[] = sprintf("    [%s, %s, %s, %s, %s, %s, %s, %s, %s, [\n%s\n    ]],", $text($schema), $text($name), $text($type), $text($engine), $version === null ? 'null' : (int) $version, $text($format), $text($collation), $text($options), $text($comment), implode("\n", $columns));
}
$version = $mysqli->query('SELECT @@version')->fetch_row()[0];
echo "<?php\n\n/**\n * The system tables of MySQL {$version}: the tables of information_schema, mysql and performance_schema.\n *\n * Each entry: database, table, table type, engine, version, row format, collation, create options, comment, and\n * its columns. Each column: name; the column, table and database a result reports it reads; how a read of it is\n * typed, as a result reports it: field code, length in characters, decimals, column flags, collation, coercibility; and as\n * INFORMATION_SCHEMA.COLUMNS lists it: column type, nullability, default, key, extra, comment and collation.\n * Generated by bin/system-tables.php from a server of the release.\n */\n\ndeclare(strict_types=1);\n\nreturn [\n" . implode("\n", $entries) . "\n];\n";
