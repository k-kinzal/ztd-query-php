<?php

/**
 * Samples general_ci BMP weights through SQL and writes the nonidentity pages.
 *
 * Usage: php bin/general-weights.php <dsn> <user> <password> > resources/general-ci-weights.php
 * The mapping has been compared byte-for-byte on MySQL 5.6.51 and 8.4.7.
 */

declare(strict_types=1);

$pdo = new PDO($argv[1], $argv[2], $argv[3], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$pages = [];
for ($page = 0; $page < 256; $page++) {
    if ($page >= 0xd8 && $page <= 0xdf) {
        continue;
    }
    $text = '';
    $identity = '';
    for ($offset = 0; $offset < 256; $offset++) {
        $point = $page * 256 + $offset;
        $text .= mb_chr($point, 'UTF-8');
        $identity .= pack('n', $point);
    }
    $hex = bin2hex($text);
    $weight = strtolower((string) $pdo->query("SELECT HEX(WEIGHT_STRING(CONVERT(UNHEX('$hex') USING utf8mb4) COLLATE utf8mb4_general_ci))")->fetchColumn());
    if (strlen($weight) !== 1024) {
        throw new RuntimeException('A general_ci BMP page must contain 256 two-byte weights.');
    }
    if ($weight !== bin2hex($identity)) {
        $pages[] = "    $page => '$weight',";
    }
}
echo "<?php\n\n/**\n * Nonidentity 256-code-point pages of general_ci primary weights, as hexadecimal.\n *\n * Generated by bin/general-weights.php through SQL, without reading server source.\n * Identical on MySQL 5.6.51 and 8.4.7. Omitted BMP pages map each code point\n * to itself; surrogate pages cannot be supplied as valid Unicode.\n */\n\ndeclare(strict_types=1);\n\nreturn [\n" . implode("\n", $pages) . "\n];\n";
