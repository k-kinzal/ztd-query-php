    /**
     * Gives the native case-equivalence key without changing accents or spacing.
     */
    public function key(string $name): string
    {
        return preg_match('/[\x80-\xff]/', $name) === 1
            ? strtr($name, self::LOWER)
            : Comparison::AsciiInsensitive->fold($name);
    }

    /**
     * Gives the assigned native alias bytes before the client displays the heading.
     */
    public function prefix(string $requested): string
    {
        return substr(ltrim($requested, "\x00..\x20\x7f"), 0, 256);
    }

    /**
     * Checks whether the assigned native bytes can be written as a UTF-8 identifier.
     */
    public function readable(string $requested): bool
    {
        return preg_match('//u', $this->prefix($requested)) === 1;
    }
